#!/usr/bin/env python3
"""Tests for signoff/verify-pin-restatements.py (the pin-restatement guard).

Stdlib ``unittest`` only, so the CI job that runs the guard needs no pip
install. Fixtures are throwaway git repositories in temporary directories;
nothing under the real repository is written.

Run (CI: ``.github/workflows/doc-citations.yml``)::

    python3 -I signoff/test_verify_pin_restatements.py

``pytest`` collects it too.
"""

from __future__ import annotations

import importlib.util
import json
import subprocess
import tempfile
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent
_SPEC = importlib.util.spec_from_file_location(
    "verify_pin_restatements", HERE / "verify-pin-restatements.py"
)
vpr = importlib.util.module_from_spec(_SPEC)
_SPEC.loader.exec_module(vpr)

RUN_CHECKS = """\
#!/usr/bin/env bash
# Toolchain pin: see KLT_VERSION_EXPECTED below; the committed layout was
# generated by the pinned build.
KLT_VERSION_EXPECTED="0.4.0"
KLAYOUT_VERSION_EXPECTED="0.30.12"

# The ERC step runs its own pinned build, one line below.
ERC_KLT=(uv run --quiet --with "klayout-tools==0.8.0" klt)
"""

SIGNOFF_YML = """\
name: signoff
jobs:
  grade:
    steps:
      - run: python -m pip install "klayout-tools==0.8.0"
"""

REGEN_NETLIST = """\
#!/usr/bin/env bash
# Netlisting runs on its own pin, KLT_NETLIST_VERSION_EXPECTED below.
KLT_NETLIST_VERSION_EXPECTED="0.9.2"
"""

EMPTY_SIDECAR = {"_comment": "test sidecar", "exemptions": []}


class FixtureRepo:
    def __init__(self, files: dict[str, str]):
        self._tmp = tempfile.TemporaryDirectory()
        self.root = Path(self._tmp.name)
        subprocess.run(["git", "init", "-q"], cwd=self.root, check=True)
        for rel, text in files.items():
            p = self.root / rel
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text)
        subprocess.run(["git", "add", "-A"], cwd=self.root, check=True)

    def close(self):
        self._tmp.cleanup()


def base_files() -> dict[str, str]:
    return {
        "layout/run_checks.sh": RUN_CHECKS,
        ".github/workflows/signoff.yml": SIGNOFF_YML,
        "design/regen-netlist.sh": REGEN_NETLIST,
        "signoff/pin-restatements.json": json.dumps(EMPTY_SIDECAR, indent=2) + "\n",
        "docs/clean.md": (
            "# Clean doc\n\nThe geometry pin is declared in layout/run_checks.sh\n"
            "(KLT_VERSION_EXPECTED); the netlist pin in design/regen-netlist.sh.\n"
        ),
    }


class PinRestatementGuardTest(unittest.TestCase):
    def make(self, extra: dict[str, str] | None = None) -> Path:
        files = base_files()
        files.update(extra or {})
        repo = FixtureRepo(files)
        self.addCleanup(repo.close)
        return repo.root

    def sidecar(self, root: Path, exemptions: list[dict]) -> None:
        (root / "signoff" / "pin-restatements.json").write_text(
            json.dumps({"_comment": "test", "exemptions": exemptions}, indent=2) + "\n"
        )

    def test_clean_tree_passes(self):
        root = self.make()
        self.assertEqual(vpr.find_findings(root), [])
        self.assertEqual(vpr.main(root), 0)

    def test_restatement_of_current_pin_fails(self):
        root = self.make({"docs/drift.md": "The ERC step runs on klt 0.8.0.\n"})
        findings = vpr.find_findings(root)
        self.assertEqual(len(findings), 1)
        self.assertIn("docs/drift.md:1", findings[0])
        self.assertIn("0.8.0", findings[0])
        self.assertIn("layout/run_checks.sh", findings[0])

    def test_stale_value_fails(self):
        root = self.make({"docs/drift.md": "The grader is klt 0.7.0 today.\n"})
        findings = vpr.find_findings(root)
        self.assertEqual(len(findings), 1)
        self.assertIn("0.7.0", findings[0])
        self.assertIn("stale", findings[0])

    def test_exempt_hit_passes_each_kind(self):
        text = "The ERC step runs on klt 0.8.0.\n"
        for kind in ("file", "marker", "region"):
            with self.subTest(kind=kind):
                root = self.make({"docs/drift.md": text})
                if kind == "file":
                    exemptions = [
                        {"kind": "file", "path": "docs/drift.md",
                         "reason": "test: whole file"}
                    ]
                elif kind == "marker":
                    exemptions = [
                        {"kind": "marker", "path": "docs/drift.md", "marker": "ERC step",
                         "reason": "test: marker line"}
                    ]
                else:
                    exemptions = [
                        {"kind": "region", "path": "docs/drift.md",
                         "start": "The ERC", "end": "runs on klt",
                         "reason": "test: region"}
                    ]
                self.sidecar(root, exemptions)
                self.assertEqual(vpr.find_findings(root), [], kind)

    def test_prefix_exemption_covers_nested_files(self):
        root = self.make({"sim/bench/README.md": "Run used klt 0.7.0.\n"})
        self.assertEqual(len(vpr.find_findings(root)), 1)
        self.sidecar(root, [
            {"kind": "prefix", "path": "sim/", "reason": "test: campaign records"}
        ])
        self.assertEqual(vpr.find_findings(root), [])

    def test_substring_version_is_not_the_pin(self):
        # 0.9.20 must be reported as its own value, never matched as 0.9.2.
        root = self.make({"docs/drift.md": "netlisted under klt 0.9.20\n"})
        findings = vpr.find_findings(root)
        self.assertEqual(len(findings), 1)
        self.assertIn("0.9.20", findings[0])
        self.assertNotIn("0.9.2 ", findings[0])

    def test_non_klt_context_ignored(self):
        root = self.make({
            "docs/other.md": "| repo-skills | 0.8.0 (Aug 9) | unrelated table |\n",
        })
        self.assertEqual(vpr.find_findings(root), [])

    def test_historical_forms_skipped(self):
        root = self.make({
            "docs/history.md": (
                "the klt-0.4.0-era envelope\n"
                "a post-0.4.0 build\n"
                "the pre-0.4.0 world and the 0.4.0 era\n"
                "`0.5.0+g2b1e55e51bb8` dev build\n"
                "0.5.0's generators\n"
            ),
        })
        self.assertEqual(vpr.find_findings(root), [])

    def test_paragraph_context_catches_split_restatement(self):
        # klt mention on one line, the value on the next: still a finding.
        root = self.make({
            "docs/drift.md": "Netlisting runs on the klt build\nfrom 0.9.2 today.\n",
        })
        findings = vpr.find_findings(root)
        self.assertEqual(len(findings), 1)
        self.assertIn("docs/drift.md:2", findings[0])

    def test_shell_comment_restatement_fails_and_code_line_does_not(self):
        root = self.make({
            "layout/run_checks.sh": RUN_CHECKS + "# header: klt 0.4.0 is the pin\n",
        })
        findings = vpr.find_findings(root)
        self.assertEqual(len(findings), 1)
        self.assertIn("layout/run_checks.sh:9", findings[0])

    def test_missing_declaration_site_fails(self):
        root = self.make()
        (root / "design" / "regen-netlist.sh").unlink()
        findings = vpr.find_findings(root)
        self.assertTrue(any("netlist" in f and "declaration" in f for f in findings))

    def test_missing_sidecar_fails(self):
        root = self.make()
        (root / "signoff" / "pin-restatements.json").unlink()
        self.assertNotEqual(vpr.find_findings(root), [])

    def test_sidecar_rot_fails(self):
        root = self.make()
        self.sidecar(root, [
            {"kind": "marker", "path": "docs/clean.md", "marker": "no such marker",
             "reason": "test: stale entry"},
        ])
        findings = vpr.find_findings(root)
        self.assertTrue(any("pin-restatements.json" in f for f in findings))

    def test_sidecar_entry_without_reason_fails(self):
        root = self.make()
        self.sidecar(root, [
            {"kind": "file", "path": "docs/clean.md"},
        ])
        self.assertTrue(any("reason" in f for f in vpr.find_findings(root)))

    def test_declarations_are_read_not_hardcoded(self):
        # Bump the fixture's ERC and grader pins to 0.8.1; prose must now
        # read 0.8.1 as the restated pin and 0.8.0 as stale.
        root = self.make({
            "layout/run_checks.sh": RUN_CHECKS.replace(
                'klayout-tools==0.8.0', 'klayout-tools==0.8.1'),
            ".github/workflows/signoff.yml": SIGNOFF_YML.replace(
                'klayout-tools==0.8.0', 'klayout-tools==0.8.1'),
            "docs/drift.md": "ERC uses klt 0.8.1; grader was klt 0.8.0.\n",
        })
        findings = vpr.find_findings(root)
        self.assertEqual(len(findings), 2)
        self.assertIn("restates the erc/grader pin", " ".join(findings))
        self.assertTrue(any("stale" in f and "0.8.0" in f for f in findings))

    def test_erc_inline_declaration_line_itself_is_not_a_finding(self):
        # The ERC_KLT line names klayout-tools==0.8.0 but is a code line,
        # not prose; the clean fixture passing above already covers it,
        # and here it stays clean even with an md-style restatement absent.
        root = self.make()
        self.assertEqual(vpr.find_findings(root), [])

    def test_real_repository_is_clean(self):
        self.assertEqual(vpr.find_findings(vpr.REPO_ROOT), [])


if __name__ == "__main__":
    unittest.main()
