#!/usr/bin/env python3
"""Fail when WORK_PLAN.md's generated plan region holds hand annotations.

The region between ``<!-- guide:plan-body:start -->`` and
``<!-- guide:plan-body:end -->`` is regenerated by the Loom Guide role's
``render_plan_body()`` and compared byte-for-byte against its output to
decide whether to write at all, so anything inside the markers the renderer
cannot emit is silently deleted on the next Guide tick — and a
``_Generated:`` timestamp line can never be byte-identical to the next
render, forcing a spurious diff (and a docs PR) on every tick that survives
only the time-based debounce (issue #448; history: PRs #445/#446/#447).

Inside the markers only, this guard fails on:

- any ``_Generated:`` line (the renderer emits none);
- any ``*(tag)*`` suffix — in the contiguous ``*(tag)*`` run at the end of
  a line — other than the renderer's own ``*(curated)*`` /
  ``*(architect)*`` / ``*(hermit)*`` (the run is checked per suffix, so
  ``*(curated)* *(held)*`` fails on ``*(held)*`` only). A ``*(tag)*``
  earlier on the line is issue-title text the renderer interpolates
  verbatim, not an annotation, so it is never flagged (issue #452);

and on missing, duplicated or out-of-order markers. Text outside the
markers is never checked.

PDK-free and stdlib-only. Run from anywhere in the repository (CI:
``.github/workflows/doc-citations.yml``)::

    python3 -I signoff/verify-work-plan-region.py

Exit 0 = the region holds only renderer-emittable text; exit 1 = findings,
one per line, each naming ``WORK_PLAN.md:<line>``.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
PLAN_NAME = "WORK_PLAN.md"
START_MARKER = "<!-- guide:plan-body:start -->"
END_MARKER = "<!-- guide:plan-body:end -->"
GENERATED_NEEDLE = "_Generated:"
SUFFIX_RE = re.compile(r"\*\(([^)]*)\)\*")
# render_plan_body()'s templates append the suffix after the issue title,
# so a renderer-emittable suffix always sits in the contiguous *(tag)* run
# at the end of the line. A *(tag)* earlier on the line is title text
# interpolated verbatim (issue #452), so only this run is checked.
TRAILING_RUN_RE = re.compile(r"(?:\s*\*\([^)]*\)\*)+\s*$")
# The only bullet suffixes render_plan_body() can emit: the imp/curated/epics
# jq templates in .loom/roles/guide.md append exactly *(curated)*,
# *(architect)* or *(hermit)* (as of 17ba6237, 2026-11-20; re-check those
# templates before extending this set).
ALLOWED_SUFFIXES = frozenset({"curated", "architect", "hermit"})


def _occurrences(text: str, marker: str) -> list[int]:
    offsets, i = [], text.find(marker)
    while i != -1:
        offsets.append(i)
        i = text.find(marker, i + 1)
    return offsets


def _line_at(text: str, offset: int) -> int:
    return text.count("\n", 0, offset) + 1


def find_findings(root: Path) -> list[str]:
    plan = root / PLAN_NAME
    if not plan.is_file():
        return [f"{PLAN_NAME}: file not found; the Guide-generated plan "
                "region cannot be checked"]
    text = plan.read_text(encoding="utf-8")
    findings: list[str] = []

    starts = _occurrences(text, START_MARKER)
    ends = _occurrences(text, END_MARKER)
    if not starts:
        findings.append(f"{PLAN_NAME}: missing {START_MARKER} marker")
    elif len(starts) > 1:
        findings.append(f"{PLAN_NAME}:{_line_at(text, starts[1])}: "
                        f"duplicate {START_MARKER} marker")
    if not ends:
        findings.append(f"{PLAN_NAME}: missing {END_MARKER} marker")
    elif len(ends) > 1:
        findings.append(f"{PLAN_NAME}:{_line_at(text, ends[1])}: "
                        f"duplicate {END_MARKER} marker")
    if len(starts) != 1 or len(ends) != 1:
        return findings

    start_off, end_off = starts[0], ends[0]
    if end_off < start_off:
        findings.append(
            f"{PLAN_NAME}:{_line_at(text, end_off)}: {END_MARKER} appears "
            f"before {START_MARKER} (markers out of order)"
        )
        return findings

    allowed = ", ".join(f"*({s})*" for s in sorted(ALLOWED_SUFFIXES))
    region_off = start_off + len(START_MARKER)
    pos = 0
    for line in text[region_off:end_off].split("\n"):
        line_no = _line_at(text, region_off + pos)
        if GENERATED_NEEDLE in line:
            findings.append(
                f"{PLAN_NAME}:{line_no}: '{GENERATED_NEEDLE}' line inside "
                "the plan-body region; render_plan_body() emits no such "
                "line, so it forces a spurious diff on every Guide tick "
                "(issue #448)"
            )
        run = TRAILING_RUN_RE.search(line)
        if run:
            for m in SUFFIX_RE.finditer(run.group(0)):
                tag = m.group(1)
                if tag not in ALLOWED_SUFFIXES:
                    findings.append(
                        f"{PLAN_NAME}:{line_no}: suffix '*({tag})*' inside the "
                        "plan-body region is not one render_plan_body() can "
                        f"emit (allowed: {allowed})"
                    )
        pos += len(line) + 1
    return findings


def main(root: Path = REPO_ROOT) -> int:
    findings = find_findings(root)
    if findings:
        print(f"{PLAN_NAME} plan-body region check failed:")
        for f in findings:
            print(f"  {f}")
        return 1
    print(f"OK: {PLAN_NAME} plan-body region holds only text "
          "render_plan_body() can emit")
    return 0


if __name__ == "__main__":
    sys.exit(main())
