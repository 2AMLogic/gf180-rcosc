#!/usr/bin/env python3
"""Generate the T1 item-5 `klt sim` corner requests for rcosc_top (issues #185, #201).

Item 5 ("full corner verification vs a ratified spec") needs a corner-matrix
`klt sim` envelope for every DR-0019 ratified row that a corner can decide.
This script writes the testbenches and requests; it does NOT launch ngspice.
Each request carries the full process x temperature grid (21 corners), so a
multi-corner submit goes to the batch fleet (KLT_SIM_BACKEND=batch) -- never a
hand-launched local grid.  See sim/item5/ROWS.md for the row-to-request map and
the declared gaps.

DUT (issues #201, #229, #235): the settled sizing of #66 / DR-0023, "P3" -- the extracted
netlist with the nine trim-ladder poly resistors at 0.70x length and the PDK cap_mim_1f0fF
timing MiM -- of the revised comparator-H layout (DR-0028), copied byte-for-byte from
sim/cmph-fix/rcosc_top_p3_cmphfix.spice.  (The pre-fix netlist is sim/recentre/p3/rcosc_top_p3.spice,
which the earlier results/20261106T051832Z campaign measured.)  The requests are therefore
`netlist_source: "extracted"` and the lumped layout parasitics are back-annotated.

One request per (trim code, VDD): the frequency `.meas` needs the VDD/2 edge
threshold at authoring time and `klt sim`'s supply axis can only `alter` a
source, the same constraint sim/startup/ and sim/pvt-postlayout/klt-pex/ work
under.  Corner definitions are imported from sim/pvt/pvt_sweep.py, not
re-typed.  Measurements per point: fosc (20 periods after skipping 5 edges,
identical to sim/pvt/pvt_sweep.py) and iq_run_ua (-i(vdd) averaged over the
fixed 200-1200 ns running window, ~48 periods, the quantity DR-0003 Row 4
names; a file-scope `.meas` cannot read the ta/tb edge times, so the window
is time-based rather than whole-period).  Only the two corner-wide limits above are declared; the
accuracy rows are post-trim percentages against a per-die calibrated reference,
not absolute per-corner limits, so their grading is report_rows.py post-processing.

Codes: 0x00 and 0xFF (range endpoints, rows 2/3), 0x80 (mid-scale untrimmed
code, row 3), 0xA4 (the tt 27 C / 3.3 V calibration code of DR-0029, which amends DR-0023's
0xA9 for the comparator-H-fixed P3 netlist, rows 1/4/5/7/8/10) and 0xA5 (its neighbour, for the LSB step, row 2).
One code is held across all 7 process corners: these requests do not
recalibrate per die (the per-process-code picture is sim/recentre's grid).

Usage:  python3 gen_requests.py [--out DIR]     # default: sim/item5/requests
Output is deterministic: regenerating is byte-identical.
"""
import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
sys.path.insert(0, str(REPO / "sim" / "pvt"))
from pvt_sweep import PROCESS_CORNERS, TEMPS_C, VDDS_V  # noqa: E402

# Calibration code: DR-0029 (amends DR-0023) re-centres it to 0xA4 on the comparator-H-fixed netlist;
# the neighbour for the LSB step is CAL_CODE + 1.  `--cal-code` regenerates for another code.
CAL_CODE = 0xA4
CODES = [0x00, 0x80, CAL_CODE, CAL_CODE + 1, 0xFF]
IQ_MAX_UA = 500.0
# `klt signoff` grades item 5 only from envelopes with at least one checked
# limit.  The only corner-wide limits that state a ratified row faithfully are
# (a) Iq < 500 uA (row 8, calibration-code requests) and (b) "a clock is
# produced" at every corner (rows 7/10: supply and temperature operating
# range).  The accuracy / range / spread rows are not corner-wide limits (they
# are nominal-point, per-die-calibrated or relative quantities): they are
# graded by report_rows.py, which quotes the ratified number and the binding corner.
OSC_PRESENT_HZ = 1.0e6
SRC = REPO / "sim" / "cmph-fix" / "rcosc_top_p3_cmphfix.spice"   # DR-0028 netlist (pre-fix: sim/recentre/p3/)
DUT = "rcosc_top_p3.spice"


def dut_text() -> str:
    return SRC.read_text()


def tag(code: int, vdd: float) -> str:
    return f"c{code:02x}_v{int(round(vdd * 10)):02d}"


def testbench(code: int, vdd: float) -> str:
    lines = [
        f"* rcosc_top item-5 corner bench, VDD={vdd:g} V, trim code 0x{code:02X} (generated by gen_requests.py)",
        ".param sw_stat_global=0 sw_stat_mismatch=0 mc_skew=3 res_mc_skew=3 cap_mc_skew=3 fnoicor=0",
        f'.include "{DUT}"',
        "XXDUT vdd 0 clk t0 t1 t2 t3 t4 t5 t6 t7 rcosc_top",
        f"VDD vdd 0 DC {vdd:g}",
        "BIQ iq_ua 0 V=-1e6*i(VDD)",
    ]
    for i in range(8):
        lines.append(f"VT{i} t{i} 0 DC {vdd * ((code >> i) & 1):g}")
    return "\n".join(lines) + "\n"


def request(code: int, vdd: float) -> dict:
    vmid = vdd / 2
    iq = {"name": "iq_run_ua",
          "spice": ".meas tran iq_run_ua AVG v(iq_ua) FROM=200n TO=1200n", "unit": "uA"}
    if code == CAL_CODE:
        iq["limits"] = {"max": IQ_MAX_UA}   # row 8, ratified < 500 uA
    return {
        "netlist": f"tb_{tag(code, vdd)}.spice",
        "engine": "ngspice",
        "netlist_source": "extracted",
        "models": {"pdk": "gf180mcuC", "lib": "libs.tech/ngspice/sm141064.ngspice"},
        "corners": {
            "process": [{"name": n, "sections": [*PROCESS_CORNERS[n], "cap_mim"]}
                        for n in PROCESS_CORNERS],
            "temperature_c": TEMPS_C,
        },
        "analysis": {"kind": "tran", "args": "200p 1200n"},
        "measurements": [
            {"name": "ta", "spice": f".meas tran ta WHEN v(clk)={vmid:.4f} RISE=5", "unit": "s"},
            {"name": "tb", "spice": f".meas tran tb WHEN v(clk)={vmid:.4f} RISE=25", "unit": "s"},
            {"name": "fosc", "spice": ".meas tran fosc PARAM='20/(tb-ta)'", "unit": "Hz",
             "limits": {"min": OSC_PRESENT_HZ}},
            iq,
        ],
        "batch": {"capacity_wait_s": 1200},
        "options": {"timeout_s": 3600, "keep_artifacts": True,
                    "ngspice_init": ["set measureprec=8"]},
    }


def generate(out: Path) -> list[Path]:
    out.mkdir(parents=True, exist_ok=True)
    written = []

    def put(name: str, text: str) -> None:
        (out / name).write_text(text)
        written.append(out / name)

    put(DUT, dut_text())
    for code in CODES:
        for vdd in VDDS_V:
            t = tag(code, vdd)
            put(f"tb_{t}.spice", testbench(code, vdd))
            put(f"request_{t}.json", json.dumps(request(code, vdd), indent=2) + "\n")
    return written


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=HERE / "requests")
    ap.add_argument("--dut", type=Path, default=None,
                    help="netlist to copy in as rcosc_top_p3.spice instead of the default "
                         "(sim/cmph-fix/rcosc_top_p3_cmphfix.spice, DR-0028)")
    ap.add_argument("--cal-code", type=lambda x: int(x, 0), default=CAL_CODE,
                    help="calibration trim code (default 0xA4, DR-0029); the LSB-step neighbour is code+1")
    a = ap.parse_args()
    if a.dut is not None:
        globals()["SRC"] = a.dut.resolve()
    globals()["CAL_CODE"] = a.cal_code
    globals()["CODES"] = [0x00, 0x80, a.cal_code, a.cal_code + 1, 0xFF]
    generate(a.out)


if __name__ == "__main__":
    main()
