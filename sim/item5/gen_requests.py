#!/usr/bin/env python3
"""Generate the T1 item-5 `klt sim` corner requests for rcosc_top (issue #185).

Item 5 ("full corner verification vs a ratified spec") needs a corner-matrix
`klt sim` envelope for every DR-0019 ratified row that a corner can decide.
This script writes the testbenches and requests; it does NOT launch ngspice.
Each request carries the full process x temperature grid (21 corners), so a
multi-corner submit goes to the batch fleet (KLT_SIM_BACKEND=batch) -- never a
hand-launched local grid.  The run itself waits on #66 (settled sizing) and a
`gf180mcuC` batch runner; see sim/item5/ROWS.md for the row-to-request map and
the declared gaps.

One request per (trim code, VDD): the frequency `.meas` needs the VDD/2 edge
threshold at authoring time and `klt sim`'s supply axis can only `alter` a
source, the same constraint sim/startup/ and sim/pvt-postlayout/klt-pex/ work
under.  Corner definitions are imported from sim/pvt/pvt_sweep.py, not
re-typed.  Measurements per point: fosc (20 periods after skipping 5 edges,
identical to sim/pvt/pvt_sweep.py) and iq_run_ua (-i(vdd) averaged over the
fixed 200-1200 ns running window, ~48 periods, the quantity DR-0003 Row 4
names; a file-scope `.meas` cannot read the ta/tb edge times, so the window
is time-based rather than whole-period).  No `limits` are declared: the
accuracy rows are post-trim percentages against a per-die calibrated reference,
not absolute per-corner limits, so row grading is a post-processing step on the
envelope, not a property of this request.

Codes: 0x00 and 0xFF (range endpoints, rows 2/3), 0x80 (mid-scale untrimmed
code, row 3), 0xA3 (the post-#60 calibration code, rows 1/4/5/7/8/10) and 0xA4
(its neighbour, for the LSB step, row 2).

Usage:  python3 gen_requests.py [--out DIR]     # default: sim/item5/requests
Output is deterministic: regenerating is byte-identical.
"""
import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
sys.path.insert(0, str(REPO / "sim" / "pvt"))
from pvt_sweep import PROCESS_CORNERS, TEMPS_C, VDDS_V  # noqa: E402

CODES = [0x00, 0x80, 0xA3, 0xA4, 0xFF]
SRC = REPO / "design" / "netlist" / "pvt_tb.spice"
DUT = "rcosc_top_schematic.spice"


def dut_text() -> str:
    text = SRC.read_text().splitlines()
    start = next(i for i, l in enumerate(text) if "expanding" in l and "rcosc_top.sym" in l)
    end = next(i for i, l in enumerate(text) if l.strip() == ".end")
    block = [l for l in text[start:end] if not l.startswith(("** sym_path:", "** sch_path:"))]
    return (
        "* schematic DUT for the item-5 corner requests: pvt_tb.spice's embedded rcosc_top hierarchy\n"
        "* (generated by gen_requests.py; no device or connection edited)\n"
        + "\n".join(block) + "\n")


def tag(code: int, vdd: float) -> str:
    return f"c{code:02x}_v{int(round(vdd * 10)):02d}"


def testbench(code: int, vdd: float) -> str:
    lines = [
        f"* rcosc_top item-5 corner bench, VDD={vdd:g} V, trim code 0x{code:02X} (generated by gen_requests.py)",
        ".param sw_stat_global=0 sw_stat_mismatch=0 mc_skew=3 res_mc_skew=3 cap_mc_skew=3 fnoicor=0",
        f'.include "{DUT}"',
        "XXDUT vdd 0 clk t0 t1 t2 t3 t4 t5 t6 t7 rcosc_top",
        f"VDD vdd 0 DC {vdd:g}",
        "BIQ iq_ua 0 V=-1e6*i(VDD)",
    ]
    for i in range(8):
        lines.append(f"VT{i} t{i} 0 DC {vdd * ((code >> i) & 1):g}")
    return "\n".join(lines) + "\n"


def request(code: int, vdd: float) -> dict:
    vmid = vdd / 2
    return {
        "netlist": f"tb_{tag(code, vdd)}.spice",
        "engine": "ngspice",
        "netlist_source": "schematic",
        "models": {"pdk": "gf180mcuC", "lib": "libs.tech/ngspice/sm141064.ngspice"},
        "corners": {
            "process": [{"name": n, "sections": [*PROCESS_CORNERS[n], "cap_mim"]}
                        for n in PROCESS_CORNERS],
            "temperature_c": TEMPS_C,
        },
        "analysis": {"kind": "tran", "args": "200p 1200n"},
        "measurements": [
            {"name": "ta", "spice": f".meas tran ta WHEN v(clk)={vmid:.4f} RISE=5", "unit": "s"},
            {"name": "tb", "spice": f".meas tran tb WHEN v(clk)={vmid:.4f} RISE=25", "unit": "s"},
            {"name": "fosc", "spice": ".meas tran fosc PARAM='20/(tb-ta)'", "unit": "Hz"},
            {"name": "iq_run_ua",
             "spice": ".meas tran iq_run_ua AVG v(iq_ua) FROM=200n TO=1200n", "unit": "uA"},
        ],
        "batch": {"capacity_wait_s": 1200},
        "options": {"timeout_s": 600, "keep_artifacts": True,
                    "ngspice_init": ["set measureprec=8"]},
    }


def generate(out: Path) -> list[Path]:
    out.mkdir(parents=True, exist_ok=True)
    written = []

    def put(name: str, text: str) -> None:
        (out / name).write_text(text)
        written.append(out / name)

    put(DUT, dut_text())
    for code in CODES:
        for vdd in VDDS_V:
            t = tag(code, vdd)
            put(f"tb_{t}.spice", testbench(code, vdd))
            put(f"request_{t}.json", json.dumps(request(code, vdd), indent=2) + "\n")
    return written


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=HERE / "requests")
    generate(ap.parse_args().out)


if __name__ == "__main__":
    main()
