#!/usr/bin/env python3
"""Post-process the settled-netlist startup `klt sim` reports (issue #227).

Reuses `analyse` and the DR-0020 band/tail constants from sim/startup/startup_report.py
(imported read-only, not edited) so the verdict definition is the same one #82 uses; only
the DUT (settled P3, code 0xA9) and the output directory differ.
Usage: python3 -I settled_report.py report_v30.json report_v33.json report_v36.json \
           --vdd 3.0 3.3 3.6 --artifacts-root OUT/v30 OUT/v33 OUT/v36 [--runid ID] [--note TEXT]
Output: results/<runid>/{results.csv,summary.md,manifest.json}; refuses to overwrite.
"""
import argparse
import csv
import datetime
import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
from _module_loader import load_module  # noqa: E402
import evidence_common  # noqa: E402  shared sha256/banner/new-run guard (#260)

sr = load_module("startup_report", HERE.parent / "startup" / "startup_report.py", reuse=True)


def verdict(r):
    if r["status"] != "STARTED":
        return "FAIL: " + r["status"]
    t = r.get(f"t_settle_{sr.PRIMARY}_ns")
    if t is None:
        return "FAIL: not within band at end of run"
    return "pass" if t <= sr.SPEC_US * 1e3 else "FAIL: > 10 us"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("reports", nargs="+")
    ap.add_argument("--vdd", nargs="+", type=float, required=True)
    ap.add_argument("--artifacts-root", nargs="+", required=True)
    ap.add_argument("--runid", default=datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%dT%H%M%SZ"))
    ap.add_argument("--note", default="")
    a = ap.parse_args()
    out = HERE / "results" / a.runid
    evidence_common.require_absent(out)
    rows, remotes = [], []
    for k, rep in enumerate(a.reports):
        d = json.load(open(rep))
        vdd = a.vdd[k]
        rem = (d.get("environment") or {}).get("remote") or {}
        remotes.append({"report": Path(rep).name, "vdd_v": vdd, "status": d.get("status"),
                        "corner_count": d.get("corner_count"), "job_id": rem.get("job_id"),
                        "runner_klt_version": rem.get("runner_klt_version"),
                        "client_klt_version": rem.get("client_klt_version"),
                        "provider": rem.get("provider")})
        for c in d["corners"]:
            row = {"process": c["process"], "temp_c": c["temperature_c"], "vdd_v": vdd,
                   "klt_status": c["status"], "t_first_edge_ns": None}
            for m in c.get("measurements", []):
                if m["name"] == "t_first_edge" and m["value"] is not None:
                    row["t_first_edge_ns"] = m["value"] * 1e9
            wf = (c.get("artifacts") or {}).get("waveform")
            wf = str(Path(a.artifacts_root[k]) / Path(wf).parent.name / Path(wf).name) if wf else None
            if not wf or not Path(wf).exists():
                row["status"] = "NO-DATA (waveform missing)"
                row["diag"] = json.dumps(c.get("diagnostics", []))[:300]
            else:
                r, _ = sr.analyse(wf, vdd)
                row.update(r)
            rows.append(row)
    out.mkdir(parents=True)
    fields = ["process", "temp_c", "vdd_v", "status", "klt_status", "n_edges", "f_settled_mhz", "tail_dev_pct",
              "t_first_edge_ns"] + [f"t_settle_{l}_ns" for l, _ in sr.BANDS] + ["clk_min_v", "clk_max_v", "diag"]
    with open(out / "results.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=fields, extrasaction="ignore")
        w.writeheader()
        for r in rows:
            w.writerow({k: (f"{v:.4g}" if isinstance(v, float) else v) for k, v in r.items()})
    n = len(rows)
    npass = sum(verdict(r) == "pass" for r in rows)
    nostart = [r for r in rows if r["status"] == "NON-START"]
    json.dump({"runid": a.runid, "klt": subprocess.run(["klt", "--version"], capture_output=True, text=True).stdout.strip(),
               "dut": "sim/recentre/p3/rcosc_top_p3.spice (settled P3, DR-0023)", "trim_code": "0xA9",
               "ramp_ns": sr.RAMP_NS, "tail_ns": sr.TAIL_NS, "tail_tol": sr.TAIL_TOL, "spec_us": sr.SPEC_US,
               "bands": dict(sr.BANDS), "primary_band": sr.PRIMARY, "sim_reports": remotes, "note": a.note,
               "primary_band_pass": npass, "total": n, "points": rows}, open(out / "manifest.json", "w"), indent=2)
    us = lambda v: "—" if v is None else "%.3f" % (v / 1e3)
    L = [f"# Startup-time sweep on the settled netlist {a.runid} (issue #227)", "",
         "Generated by `sim/startup-settled/settled_report.py` (analysis reused from `sim/startup/startup_report.py`)",
         f"from `klt sim` reports of `sim/startup-settled/request_v*.json`. DUT: settled P3 netlist, trim code 0xA9.",
         f"t = 0 is the start of a {sr.RAMP_NS} ns linear 0 -> VDD ramp. Spec: startup time <= {sr.SPEC_US:g} us;",
         f"primary band {sr.PRIMARY} (DR-0020). Append-only evidence.", "",
         *([f"**Run note: {a.note}**", ""] if a.note else []),
         "## Batch job provenance", ""]
    for x in remotes:
        L.append(f"- `{x['report']}` (VDD {x['vdd_v']:g} V): status `{x['status']}`, {x['corner_count']} corners, "
                 f"{x['provider']} job `{x['job_id']}`, runner klt {x['runner_klt_version']}, client klt {x['client_klt_version']}")
    L += ["", f"## Verdict: {npass}/{n} points pass the primary band; {len(nostart)} NON-START", "",
          "| process | T (C) | VDD (V) | status | f settled (MHz) | first edge (us) | " +
          " | ".join(f"settle +/-{l} (us)" for l, _ in sr.BANDS) + " | verdict |",
          "|---|---|---|---|---|---|" + "---|" * (len(sr.BANDS) + 1)]
    for r in sorted(rows, key=lambda r: (r["vdd_v"], r["process"], r["temp_c"])):
        L.append(f"| `{r['process']}` | {r['temp_c']:g} | {r['vdd_v']:g} | {r['status']} | "
                 f"{r.get('f_settled_mhz', float('nan')):.2f} | {us(r.get('t_first_edge_ns'))} | " +
                 " | ".join(us(r.get(f"t_settle_{l}_ns")) for l, _ in sr.BANDS) + f" | {verdict(r)} |")
    (out / "summary.md").write_text("\n".join(L) + "\n")
    print(f"{npass}/{n} pass; {len(nostart)} NON-START; wrote {out}")


if __name__ == "__main__":
    main()
