#!/usr/bin/env python3
"""Row-5 re-confirmation on the REAL regenerated schematic netlist (issue #321, DR-0039 follow-up): the comparator-H mirror-load
L 0.7 um edit as committed in design/rcosc_comparator.sch, simulated from design/netlist/pvt_tb.spice's embedded rcosc_top hierarchy
(no layout parasitics, so per-die codes are re-derived by scan; DR-0038's P3 codes do not transfer).  Reuses
gen_calib_requests.py and sim/row45-attribution/gen_stage_requests.py unchanged except for the DUT text, probe nets and
netlist_source.  Launches nothing.  CONTROL_L1=1 puts MLOADA/MLOADB back to L=1u (same-netlist control).

  gen_row5_schematic.py calib OUTDIR PROC:CODE[,CODE...] [PROC:CODE,...]   per-die calibration scan (27 C / 3.3 V)
  gen_row5_schematic.py stage OUTDIR tt=CODE,ff=CODE,ss=CODE               the 9-request stage re-run at those codes
"""
import json
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
sys.path.insert(0, str(REPO / "sim" / "row45-attribution"))
sys.path.insert(0, str(HERE))
import gen_calib_requests as gc  # noqa: E402
import gen_stage_requests as gs  # noqa: E402

SRC = REPO / "design" / "netlist" / "pvt_tb.spice"
# probe pin -> schematic net (top level of rcosc_top.sch); same pin order as the extracted-netlist probes
NETS = {"pvc": "vc", "pvh": "vh", "pvl": "vl", "pcmph": "cmph_out", "pcmpl": "cmpl_out", "pqbar": "qbar", "pibias": "ibias", "ppb": "pb"}
assert [p for p, _ in gs.PROBES] == list(NETS)
HEAD = ".subckt rcosc_top vdd vss clk t0 t1 t2 t3 t4 t5 t6 t7"


def dut_text(probed: bool) -> str:
    text = SRC.read_text().splitlines()
    start = next(i for i, l in enumerate(text) if "expanding" in l and "rcosc_top.sym" in l)
    end = next(i for i, l in enumerate(text) if l.strip() == ".end")
    block = [l for l in text[start:end] if not l.startswith(("** sym_path:", "** sch_path:"))]
    if probed:
        i = block.index(HEAD)
        block[i] = HEAD + " " + " ".join(NETS)
        j = next(k for k in range(i, len(block)) if block[k].strip() == ".ends")
        block[j:j] = ["* probe taps (analysis only)"] + [f"R{p} {p} {n} 1m" for p, n in NETS.items()]
    assert sum("MLOAD" in l and "L=0.7u" in l for l in block) == 2, "schematic does not carry MLOAD L=0.7u"
    if os.environ.get("CONTROL_L1"):  # same-netlist control: put the two mirror loads back to the pre-DR-0039 L=1u
        block = [l.replace("L=0.7u", "L=1u") if "MLOAD" in l else l for l in block]
        return "* CONTROL: schematic DUT with MLOADA/MLOADB L=1u (pre-DR-0039), otherwise identical (gen_row5_schematic.py)\n" + "\n".join(block) + "\n"
    return "* schematic DUT: pvt_tb.spice's embedded rcosc_top hierarchy (generated by gen_row5_schematic.py; nothing edited)\n" + "\n".join(block) + "\n"


def as_schematic(req: dict) -> dict:
    req["netlist_source"] = "schematic"
    return req


if __name__ == "__main__":
    mode, out = sys.argv[1], Path(sys.argv[2])
    out.mkdir(parents=True, exist_ok=True)
    if mode == "calib":
        (out / gc.DUT).write_text(dut_text(False))
        for spec in sys.argv[3:]:
            proc, codes = spec.split(":")
            for c in codes.split(","):
                c = int(c, 0)
                (out / f"tb_{proc}_c{c:02X}.spice").write_text(gc.bench(c))
                (out / f"request_{proc}_c{c:02X}.json").write_text(json.dumps(as_schematic(gc.request(proc, c)), indent=2) + "\n")
    elif mode == "stage":
        gs.CODES.clear()
        gs.CODES.update({k: int(v) for k, v in (p.split("=") for p in sys.argv[3].split(","))})
        names = gs.generate(out)  # writes benches/requests (+ a DUT we overwrite below)
        (out / gs.DUT).write_text(dut_text(True))
        for n in names:
            p = out / n
            p.write_text(json.dumps(as_schematic(json.loads(p.read_text())), indent=2) + "\n")
            print(n)
    else:
        sys.exit(__doc__)
