#!/usr/bin/env python3
"""Per-die calibration scan for the #317 variant DUT (tt/ss/ff, 27 C, 3.3 V, one code per request).  Usage (BASELINE=1 leaves the DUT unmodified):
gen_calib_requests.py OUTDIR PROC:CODE[,CODE...] [PROC:CODE,...]   -- writes the variant DUT, benches and requests."""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
sys.path.insert(0, str(REPO / "sim" / "pvt"))
sys.path.insert(0, str(HERE))
from pvt_sweep import PROCESS_CORNERS  # noqa: E402
import variant  # noqa: E402

SRC = REPO / "sim" / "cmph-fix" / "rcosc_top_p3_cmphfix.spice"
DUT = "rcosc_top_variant.spice"


def dut_text() -> str:
    import os
    return SRC.read_text() if os.environ.get("BASELINE") else variant.build(SRC.read_text())


def bench(code: int, vdd: float = 3.3) -> str:
    L = [f"* #317 calibration probe code 0x{code:02X} (generated by gen_calib_requests.py)",
         ".param sw_stat_global=0 sw_stat_mismatch=0 mc_skew=3 res_mc_skew=3 cap_mc_skew=3 fnoicor=0",
         f'.include "{DUT}"', "XXDUT vdd 0 clk t0 t1 t2 t3 t4 t5 t6 t7 rcosc_top", f"VDD vdd 0 DC {vdd:g}"]
    L += [f"VT{i} t{i} 0 DC {vdd * ((code >> i) & 1):g}" for i in range(8)]
    return "\n".join(L) + "\n"


def request(proc: str, code: int, vdd: float = 3.3) -> dict:
    m = vdd / 2
    ms = [{"name": "f_ta", "spice": f".meas tran f_ta WHEN v(clk)={m:.4f} RISE=5", "unit": "s"},
          {"name": "f_tb", "spice": f".meas tran f_tb WHEN v(clk)={m:.4f} RISE=25", "unit": "s"},
          {"name": "fosc", "spice": ".meas tran fosc PARAM='20/(f_tb-f_ta)'", "unit": "Hz"}]
    return {"netlist": f"tb_{proc}_c{code:02X}.spice", "engine": "ngspice", "netlist_source": "extracted",
            "models": {"pdk": "gf180mcuC", "lib": "libs.tech/ngspice/sm141064.ngspice"},
            "corners": {"process": [{"name": proc, "sections": [*PROCESS_CORNERS[proc], "cap_mim"]}],
                        "temperature_c": [27.0]},
            "analysis": {"kind": "tran", "args": "200p 1200n"}, "measurements": ms,
            "batch": {"capacity_wait_s": 600},
            "options": {"timeout_s": 1800, "keep_artifacts": True, "ngspice_init": ["set measureprec=8"]}}


if __name__ == "__main__":
    out = Path(sys.argv[1])
    out.mkdir(parents=True, exist_ok=True)
    (out / DUT).write_text(dut_text())
    for spec in sys.argv[2:]:
        proc, codes = spec.split(":")
        for c in codes.split(","):
            c = int(c, 0)
            (out / f"tb_{proc}_c{c:02X}.spice").write_text(bench(c))
            (out / f"request_{proc}_c{c:02X}.json").write_text(json.dumps(request(proc, c), indent=2) + "\n")
