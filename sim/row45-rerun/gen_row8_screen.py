#!/usr/bin/env python3
"""Row-8 comparator-H current-lever screen on the DR-0044 extraction (issue #458, DR-0046 lever).

Simulation-only variants of the DR-0044 DUT (results/20261112T200335Z-extract-l07/,
sha256 01e06daeb8cf341189207770f982c32a4b288b3bca504614262353ef324d16a1): comparator-H
tail W factor (the X$39..X$46 fingers, MTAIL) and/or mirror-load L (X$65/X$66, MLOADA/MLOADB)
via variant.first_stage.  The generic variant.build() (bank switches x2) is NOT applied, so the
comparison isolates the comparator-H lever named by DR-0046.  Control = the unmodified DUT.
Calibration / Iq benches reuse gen_calib_requests.py and gen_row5_iq_schematic.py unchanged; the
startup bench reuses sim/startup-settled/gen_requests.py's testbench and request (corners reduced
to fs / -40 C, the historically failing corner, at 3.3 / 3.6 V).  Launches nothing.

  gen_row8_screen.py dut OUTDIR NAME                 write OUTDIR/rcosc_top_variant.spice (NAME in VARIANTS)
  gen_row8_screen.py check CONTROL NAME:OUTDIR [...]  verify only tail/load devices moved against the control
  gen_row8_screen.py calib OUTDIR NAME PROC:CODE[,CODE...] [...]
                                                     per-process calibration scan requests (27 C / 3.3 V)
  gen_row8_screen.py iq OUTDIR NAME tt=CODE,ff=CODE,ss=CODE
                                                     held-code per-process Iq/f requests + the 0xFF all-process set
  gen_row8_screen.py delay OUTDIR NAME ff=CODE       t_cmp_h probe bench (pvc/pvh/pcmph taps) at the limiting cells
  gen_row8_screen.py startup OUTDIR NAME CODE        fs / -40 C startup requests at 3.3 / 3.6 V (sim/startup-settled bench)
"""
import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
sys.path.insert(0, str(REPO / "sim" / "pvt"))
sys.path.insert(0, str(HERE))
import pvt_sweep  # noqa: E402  PROCESS_CORNERS via gc
import variant  # noqa: E402
import gen_calib_requests as gc  # noqa: E402
import gen_row5_iq_schematic as gi  # noqa: E402

SRC = HERE / "results" / "20261112T200335Z-extract-l07" / "rcosc_top_p3_cmphfix.spice"
SRC_SHA = "01e06daeb8cf341189207770f982c32a4b288b3bca504614262353ef324d16a1"

# the screened family: DR-0046's named lever (first-stage sizing), six variants + control
VARIANTS = {
    "control": {},
    "t85": {"tail_k": 0.85},
    "t70": {"tail_k": 0.70},
    "t55": {"tail_k": 0.55},
    "t40": {"tail_k": 0.40},
    "l06": {"load_l": 0.60},
    "t70l06": {"tail_k": 0.70, "load_l": 0.60},
}


def dut_text(name: str) -> str:
    source = SRC.read_bytes()
    digest = hashlib.sha256(source).hexdigest()
    if digest != SRC_SHA:
        raise ValueError(f"{SRC}: expected DR-0044 SHA-256 {SRC_SHA}, got {digest}")
    t = source.decode("utf-8")
    kw = VARIANTS[name]
    return variant.first_stage(t, **kw) if kw else t


# --- DUT diff guard: only the comparator-H tail fingers and mirror loads may move -------------
TAIL, LOADS = set(range(39, 47)), {65, 66}
ALLOWED = TAIL | LOADS


def dut_check(control_dir: Path, pairs) -> dict:
    ctl = (control_dir / gc.DUT).read_text().split("\n")
    report = {}
    for name, d in pairs:
        new = (d / gc.DUT).read_text().split("\n")
        if len(ctl) != len(new):
            raise ValueError(f"{d}: line count changed")
        moved = set()
        for lineno, (a, b) in enumerate(zip(ctl, new), 1):
            if a == b:
                continue
            old, resized = variant.DEV.fullmatch(a), variant.DEV.fullmatch(b)
            if not old or not resized or old.group(1) != resized.group(1) or int(old.group(2)) not in ALLOWED:
                raise ValueError(f"{d}:{lineno}: change outside comparator-H sizing:\n{a}\n{b}")
            moved.add(int(old.group(2)))
        report[name] = sorted(moved)
    return report


# --- t_cmp_h probe bench on the new extraction's star-hub nets ---------------------------------
# vc = $26 (CTIMING node, MDISCH drain, X$19 gate), vh = $7 (upper divider tap, X$20 gate),
# cmph_out = $32 (X$21/X$67 output inverter output; the old DR-0028 probe names do not apply).
DELAY_PROBES = [("pvc", r"\$26"), ("pvh", r"\$7"), ("pcmph", r"\$32")]
SUBCKT = ".SUBCKT rcosc_top vdd vss clk t0 t1 t2 t3 t4 t5 t6 t7"


def probed_dut(text: str) -> str:
    if text.count(SUBCKT) != 1 or text.count(".ENDS") != 1:
        raise ValueError("delay probes require exactly one rcosc_top subcircuit and one .ENDS")
    text = text.replace(SUBCKT, SUBCKT + " " + " ".join(p for p, _ in DELAY_PROBES))
    probes = "".join(f"R{p} {p} {net} 1m\n" for p, net in DELAY_PROBES)
    head, tail = text.split(".ENDS", 1)
    return head + "* probe taps (analysis only; row-8 t_cmp_h bench, issue #458)\n" + probes + ".ENDS" + tail


def delay_bench(code: int, vdd: float) -> str:
    L = [f"* row-8 t_cmp_h bench, code 0x{code:02X}, VDD={vdd:g} V (generated by gen_row8_screen.py, issue #458)",
         ".param sw_stat_global=0 sw_stat_mismatch=0 mc_skew=3 res_mc_skew=3 cap_mc_skew=3 fnoicor=0",
         f'.include "{gc.DUT}"',
         "XXDUT vdd 0 clk t0 t1 t2 t3 t4 t5 t6 t7 pvc pvh pcmph rcosc_top",
         f"VDD vdd 0 DC {vdd:g}"]
    L += [f"VT{i} t{i} 0 DC {vdd * ((code >> i) & 1):g}" for i in range(8)]
    return "\n".join(L) + "\n"


def delay_request(temps, vdd: float) -> dict:
    m = vdd / 2
    ms = [{"name": "ev_vh", "spice": ".meas tran ev_vh WHEN v(pvc)=v(pvh) RISE=1 TD=700n", "unit": "s"},
          {"name": "ev_cmph", "spice": f".meas tran ev_cmph WHEN v(pcmph)={m:.4f} RISE=1 TD=700n", "unit": "s"},
          {"name": "ev_clk", "spice": f".meas tran ev_clk WHEN v(clk)={m:.4f} RISE=1 TD=700n", "unit": "s"},
          {"name": "vh_avg", "spice": ".meas tran vh_avg AVG v(pvh) FROM=900n TO=1200n", "unit": "V"},
          {"name": "f_ta", "spice": f".meas tran f_ta WHEN v(clk)={m:.4f} RISE=5", "unit": "s"},
          {"name": "f_tb", "spice": f".meas tran f_tb WHEN v(clk)={m:.4f} RISE=25", "unit": "s"},
          {"name": "fosc", "spice": ".meas tran fosc PARAM='20/(f_tb-f_ta)'", "unit": "Hz"}]
    return {"netlist": f"tb_dly_v{int(round(vdd * 10)):02d}.spice", "engine": "ngspice",
            "netlist_source": "extracted",
            "models": {"pdk": "gf180mcuC", "lib": "libs.tech/ngspice/sm141064.ngspice"},
            "corners": {"process": [{"name": "ff", "sections": [*pvt_sweep.PROCESS_CORNERS["ff"], "cap_mim"]}],
                        "temperature_c": list(temps)},
            "analysis": {"kind": "tran", "args": "200p 1200n"}, "measurements": ms,
            "batch": {"capacity_wait_s": 600},
            "options": {"timeout_s": 1800, "keep_artifacts": True, "ngspice_init": ["set measureprec=8"]}}


# --- Iq grid: held codes per process (one process per request) + 0xFF all-process requests -----
def iq_request(proc: str, code: int, vdd: float) -> dict:
    r = gc.request(proc, code, vdd)
    r["netlist"] = f"tb_iq_{proc}_c{code:02X}_v{int(round(vdd * 10)):02d}.spice"
    r["corners"]["temperature_c"] = list(gi.TEMPS)  # gc.request pins [27]; the held-code grid needs all three
    m = vdd / 2
    r["measurements"] = r["measurements"][:2] + [
        {"name": "q_a", "spice": f".meas tran q_a FIND v(qint) WHEN v(clk)={m:.4f} RISE=5", "unit": "V"},
        {"name": "q_b", "spice": f".meas tran q_b FIND v(qint) WHEN v(clk)={m:.4f} RISE=25", "unit": "V"},
        {"name": "iq_run", "spice": ".meas tran iq_run PARAM='(q_b-q_a)*1n/(f_tb-f_ta)'", "unit": "A"}]
    r["analysis"] = {"kind": "tran", "args": "200p 4000n"}
    return r


def _startup_gen():
    sys.path.insert(0, str(REPO / "sim" / "startup-settled"))
    import gen_requests  # noqa: E402  sim/startup-settled bench, reused read-only
    return gen_requests


def write(out: Path, name: str, text: str) -> None:
    p = out / name
    p.write_text(text)
    print(p)


if __name__ == "__main__":
    mode = sys.argv[1]
    if mode == "dut":
        out = Path(sys.argv[2])
        out.mkdir(parents=True, exist_ok=True)
        write(out, gc.DUT, dut_text(sys.argv[3]))
    elif mode == "check":
        ctl_dir = Path(sys.argv[2])
        pairs = [(p.split(":", 1)[0], Path(p.split(":", 1)[1])) for p in sys.argv[3:]]
        for name, moved in dut_check(ctl_dir, pairs).items():
            tail = sorted(set(moved) & TAIL)
            load = sorted(set(moved) & LOADS)
            what = ("tail fingers " + ",".join(f"X${i}" for i in tail) + " " if tail else "") + \
                   ("loads " + ",".join(f"X${i}" for i in load) if load else "")
            print(f"{name}: {what or 'unmodified'}")
    elif mode == "calib":
        out, name = Path(sys.argv[2]), sys.argv[3]
        out.mkdir(parents=True, exist_ok=True)
        write(out, gc.DUT, dut_text(name))
        for spec in sys.argv[4:]:
            proc, codes = spec.split(":")
            for c in codes.split(","):
                c = int(c, 0)
                write(out, f"tb_{proc}_c{c:02X}.spice", gc.bench(c))
                write(out, f"request_{proc}_c{c:02X}.json", json.dumps(gc.request(proc, c), indent=2) + "\n")
    elif mode == "iq":
        out, name = Path(sys.argv[2]), sys.argv[3]
        codes = {k: int(v, 0) for k, v in (p.split("=") for p in sys.argv[4].split(","))}
        out.mkdir(parents=True, exist_ok=True)
        write(out, gc.DUT, dut_text(name))
        for proc, code in sorted(codes.items()):
            for vdd in gi.VDDS:
                r = iq_request(proc, code, vdd)
                write(out, r["netlist"], gc.bench(code, vdd) + gi.INTEG_LINES)
                write(out, f"request_iq_{proc}_c{code:02X}_v{int(round(vdd * 10)):02d}.json",
                      json.dumps(r, indent=2) + "\n")
        for vdd in gi.VDDS:  # the 0xFF set, one request per supply over all processes (DR-0044 shape)
            r = gi.request(gi.PROCS, 0xFF, vdd)
            r["netlist_source"] = "extracted"  # the DUT here is the DR-0044 extraction variant, not the schematic
            write(out, r["netlist"], gc.bench(0xFF, vdd) + gi.INTEG_LINES)
            write(out, f"request_iq_cFF_v{int(round(vdd * 10)):02d}.json", json.dumps(r, indent=2) + "\n")
    elif mode == "delay":
        out, name = Path(sys.argv[2]), sys.argv[3]
        code = int(dict(p.split("=") for p in sys.argv[4].split(","))["ff"], 0)
        out.mkdir(parents=True, exist_ok=True)
        write(out, gc.DUT, probed_dut(dut_text(name)))
        for temps, vdd in (([85.0, -40.0], 3.0), ([85.0], 3.6)):
            r = delay_request(temps, vdd)
            write(out, r["netlist"], delay_bench(code, vdd))
            write(out, f"request_dly_v{int(round(vdd * 10)):02d}.json", json.dumps(r, indent=2) + "\n")
    elif mode == "startup":
        out, name = Path(sys.argv[2]), sys.argv[3]
        code = int(sys.argv[4], 0)
        out.mkdir(parents=True, exist_ok=True)
        g = _startup_gen()
        write(out, g.DUT, dut_text(name))
        for vdd in (3.3, 3.6):
            r = g.request(vdd)
            r["corners"] = {"process": [{"name": "fs", "sections": [*pvt_sweep.PROCESS_CORNERS["fs"], "cap_mim"]}],
                            "temperature_c": [-40.0]}
            r["batch"]["capacity_wait_s"] = 600
            write(out, r["netlist"], g.testbench(vdd, code))
            write(out, f"request_{g.tag(vdd)}.json", json.dumps(r, indent=2) + "\n")
    else:
        sys.exit(__doc__)
