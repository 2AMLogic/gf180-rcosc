#!/usr/bin/env python3
"""Generate the 27-point `klt sim` corners requests for the proposed re-centre
(issue #66, AC 3).  Does NOT launch ngspice.

Proposed sizing "P3" (decision record 0023): all nine trim-ladder poly
resistors (RFIX + R0..R7) at 0.70x their committed length, timing MiM
unchanged at 20 x 10 um, expressed on the committed extracted netlist so the
layout's lumped parasitics stay back-annotated at their extracted values.
The MiM is the PDK `cap_mim_1f0fF` subckt (as design/rcosc_top.sch uses), not
the extractor's fixed-value C, so the mimcap process corner is exercised.

One request per process (the per-process calibrated trim code differs), each
a 3 (supply) x 3 (temperature) = 9-corner matrix; 3 requests = the existing
27-point subset.  Each testbench holds three DUT instances so one corner
simulation measures, at the same PVT point:
    XLO  trim 0x00     (slow end of the trim range)
    XHI  trim 0xFF     (fast end of the trim range)
    XCAL trim = that process's 27C/3.3V calibration code (post-trim point)
Measurement: rising-edge times 5 and 25 of each clk (VDD/2 crossing, the
same methodology as sim/pvt/pvt_sweep.py), frequency = 20 / (t25 - t5),
computed by report_range.py.

The supply is swept through `corners.supply_v` (VDD and the trim-high rail
VHI move together).  Submit with KLT_SIM_BACKEND=batch (the daemon default);
never as a hand-launched ngspice loop.

Usage: python3 -I sim/recentre/gen_requests.py [--probe tt:27:3.3]
"""
import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import pexlib as L  # noqa: E402

OUT = HERE / "p3"
R_SCALE = 0.70
MIM_WL = (20.0, 10.0)
CAL_CODES = {"tt": 0xA9, "ff": 0x59, "ss": 0xD7}  # explore.py calibrations, model A
PROCS = ["tt", "ff", "ss"]
TEMPS = [-40.0, 27.0, 85.0]
VDDS = [3.0, 3.3, 3.6]
TSTOP_NS = 1200
FIRST, LAST = 5, 25


def write_dut() -> None:
    cards = L.sizing(L.load_cards(), mim_wl=MIM_WL, r_scale=R_SCALE)
    text, _ = L.pex.strip_capacitor_model_annotations("\n".join(cards) + "\n")
    pins = ["vdd", "vss", "clk"] + [f"t{i}" for i in range(8)]
    text = L.pex.reorder_extracted_header(text, pins)
    OUT.mkdir(exist_ok=True)
    (OUT / "rcosc_top_p3.spice").write_text(
        "* rcosc_top, proposed re-centre P3 (issue #66, DR-0023): committed\n"
        "* extracted netlist (sim/pvt-postlayout/results/20260923T152954Z/\n"
        "* rcosc_top.pex.spice) with (a) the nine trim-ladder poly resistor\n"
        "* lengths x0.70 and (b) the fixed-value MiM C card replaced by the\n"
        "* PDK cap_mim_1f0fF subckt at 20u x 10u. Nothing else edited.\n"
        + text)


def write_tb(proc: str) -> str:
    code = CAL_CODES[proc]
    lines = [
        f"* rcosc_top P3 range/post-trim bench, {proc}: XLO 0x00, XHI 0xFF, XCAL 0x{code:02X} (generated by gen_requests.py)",
        ".param sw_stat_global=0 sw_stat_mismatch=0 mc_skew=3 res_mc_skew=3 cap_mc_skew=3 fnoicor=0",
        '.include "rcosc_top_p3.spice"',
        "VDD vdd 0 DC 3.3",
        "VHI vhi 0 DC 3.3",
        "BMID vmid 0 V=v(vdd)/2",
    ]
    for tag, c in (("LO", 0x00), ("HI", 0xFF), ("CAL", code)):
        pins = " ".join("vhi" if (c >> i) & 1 else "0" for i in range(8))
        lines.append(f"X{tag} vdd 0 clk_{tag.lower()} {pins} rcosc_top")
    lines.append(".save v(clk_lo) v(clk_hi) v(clk_cal) v(vmid)")
    name = f"tb_{proc}.spice"
    (OUT / name).write_text("\n".join(lines) + "\n")
    return name


def request(proc: str, tbname: str, temps, vdds) -> dict:
    fets, res, mim = L.base.PROCESS_CORNERS[proc]
    meas = []
    for tag in ("lo", "hi", "cal"):
        for nm, rise in (("ta", FIRST), ("tb", LAST)):
            meas.append({"name": f"{nm}_{tag}", "unit": "s",
                         "spice": f".meas tran {nm}_{tag} WHEN v(clk_{tag})=v(vmid) RISE={rise}"})
    return {
        "netlist": tbname,
        "engine": "ngspice",
        "netlist_source": "extracted",
        "models": {"pdk": "gf180mcuC", "lib": "libs.tech/ngspice/sm141064.ngspice"},
        "corners": {
            "process": [{"name": proc, "sections": [fets, res, mim, "cap_mim"]}],
            "supply_v": {"VDD": list(vdds), "VHI": list(vdds)},
            "temperature_c": list(temps),
        },
        "analysis": {"kind": "tran", "args": f"{L.base.TSTEP} {TSTOP_NS}n"},
        "measurements": meas,
        "batch": {"capacity_wait_s": 1200},
        "options": {"timeout_s": 3600, "keep_artifacts": True,
                    "ngspice_init": ["set measureprec=8"]},
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--probe", help="proc:temp:vdd -> request_probe.json (ONE corner, for --backend local)")
    a = ap.parse_args()
    write_dut()
    if a.probe:
        p, t, v = a.probe.split(":")
        tb = write_tb(p)
        req = request(p, tb, [float(t)], [float(v)])
        req.pop("batch")
        (OUT / "request_probe.json").write_text(json.dumps(req, indent=2) + "\n")
        return
    for p in PROCS:
        tb = write_tb(p)
        (OUT / f"request_{p}.json").write_text(
            json.dumps(request(p, tb, TEMPS, VDDS), indent=2) + "\n")


if __name__ == "__main__":
    main()
