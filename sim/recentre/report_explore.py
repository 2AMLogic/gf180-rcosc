#!/usr/bin/env python3
"""Collate every explore.py run (sim/recentre/results/<runid>/ holding a
command.txt that starts with sim/recentre/explore.py) into one summary
(issue #66).  Pure post-processing; refuses to overwrite.  Where several runs
hold the same (candidate, substrate, vc scale, corner, code) key, the newest
run wins, so a re-run with an intact raw log supersedes a row whose log was
overwritten (PR #158 review, see ERRATUM.md in the affected run dirs).

Usage: python3 -I sim/recentre/report_explore.py sim/recentre/results/<new-runid>
"""
import csv
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TARGET = 48.0e6
CAND_DESC = {
    "base": "committed sizing, fixed-value MiM C card as extracted (217.2 fF)",
    "base_subckt": "committed sizing, PDK cap_mim_1f0fF 20x10 subckt (corner-aware MiM)",
    "prop_r080_17x10": "P1: ladder R x0.80, MiM 17x10 um (185.6 fF)",
    "optB_r066_24x10": "P2: ladder R x0.66, MiM 24x10 um (260 fF)",
    "r070_20x10": "P3: ladder R x0.70, MiM unchanged 20x10 um (217.2 fF)",
}


def load():
    rows = {}
    for d in sorted((HERE / "results").iterdir()):
        cmd = d / "command.txt"
        if not (cmd.is_file() and cmd.read_text().split()[0].endswith("recentre/explore.py")):
            continue
        for r in csv.DictReader(open(d / "results.csv")):
            if not r["f_hz"]:
                continue
            key = (r["candidate"], r["substrate"], float(r.get("vc_c_scale") or 1), r["corner"], int(r["code"]))
            rows[key] = (float(r["f_hz"]), float(r["iq_a"]), r["log"])
    return rows


def main() -> None:
    out = Path(sys.argv[1]) / "summary.md"
    if out.exists():
        sys.exit(f"refusing to overwrite {out}")
    rows = load()
    g = lambda c, s, corner, code, v=1.0: rows.get((c, s, v, corner, code))
    L = []
    w = L.append
    w("# Re-centre exploration summary (issue #66)\n")
    w("Generated by `sim/recentre/report_explore.py` from every explore run `sim/recentre/results/<runid>/results.csv` "
      "(driver `explore.py`; each row is one serial single-corner ngspice transient, logs in "
      "`sim/recentre/corners/explore-*`; the `log` column names the raw log behind each T/V row; newest run wins "
      "per key). Model A = netlist as extracted (1 Tohm substrate shunt); "
      "model B = same with `vsubs` hard-tied to ground.\n")
    w("## Candidates\n")
    for k, v in CAND_DESC.items():
        w(f"* `{k}`: {v}")
    w("\n## Trim-range endpoints at tt / 27 C / 3.3 V (ratified range: 28.800 - 67.200 MHz)\n")
    w("| candidate | substrate | f(0x00) MHz | f(0xFF) MHz | margin below 28.8 | margin above 67.2 | ratio f(0xFF)/f(0x00) |")
    w("|---|---|---|---|---|---|---|")
    for c in ("base", "base_subckt", "prop_r080_17x10", "optB_r066_24x10", "r070_20x10"):
        for s in ("as-extracted", "hard-tied"):
            lo, hi = g(c, s, "tt:27:3.3", 0), g(c, s, "tt:27:3.3", 255)
            if lo and hi:
                w(f"| `{c}` | {s} | {lo[0]/1e6:.3f} | {hi[0]/1e6:.3f} | {100*(28.8e6/lo[0]-1):+.1f} % | {100*(hi[0]/67.2e6-1):+.1f} % | {hi[0]/lo[0]:.3f} |")
    w("\n## Calibration to 48.000 MHz at 27 C / 3.3 V (code = closest of the final bisection bracket)\n")
    w("| candidate | substrate | process | cal code | f (MHz) | error vs 48 MHz | f(code+1)/f(code)-1 (LSB) | Iq at code (uA) |")
    w("|---|---|---|---|---|---|---|---|")
    for c in ("base_subckt", "prop_r080_17x10", "optB_r066_24x10", "r070_20x10"):
        for s in ("as-extracted", "hard-tied"):
            for p in ("tt", "ff", "ss"):
                corner = f"{p}:27:3.3"
                cands = sorted((code for (cc, ss_, v, co, code) in rows if cc == c and ss_ == s and co == corner and v == 1.0))
                if len(cands) < 4:
                    continue
                best = min(cands, key=lambda k: abs(g(c, s, corner, k)[0] - TARGET))
                f0 = g(c, s, corner, best)
                f1 = g(c, s, corner, best + 1)
                lsb = f"{100*(f1[0]/f0[0]-1):.2f} %" if f1 else "n/a"
                w(f"| `{c}` | {s} | {p} | 0x{best:02X} ({best}) | {f0[0]/1e6:.3f} | {100*(f0[0]/TARGET-1):+.2f} % | {lsb} | {f0[1]*1e6:.1f} |")
    w("\n## Post-trim drift of proposed P3 at the T/V extremes of the 0xA3 27-point record\n")
    w("Per-process calibrated code held; the two extreme points per process are the min/max-frequency points "
      "of the 0xA3 27-point record (`sim/pvt-postlayout/results/20260923T152954Z/`). 9 single-corner probes per "
      "substrate model, not the 27-point grid.\n")
    for s, codes in (("as-extracted", {"tt": 0xA9, "ff": 0x59, "ss": 0xD7}), ("hard-tied", {"tt": 0xAF, "ff": 0x59, "ss": 0xE7})):
        w(f"\n### P3, substrate model {s}\n")
        w("| process | code | point | f (MHz) | vs 48 MHz | vs own 27C/3.3V calibration point | log |")
        w("|---|---|---|---|---|---|---|")
        pts = {"tt": ["tt:27:3.3", "tt:-40:3", "tt:85:3.6"], "ff": ["ff:27:3.3", "ff:-40:3.6", "ff:85:3"], "ss": ["ss:27:3.3", "ss:-40:3", "ss:85:3.6"]}
        for p, plist in pts.items():
            ref = g("r070_20x10", s, plist[0], codes[p])
            for pt in plist:
                r = g("r070_20x10", s, pt, codes[p])
                if r and ref:
                    w(f"| {p} | 0x{codes[p]:02X} | {pt} | {r[0]/1e6:.3f} | {100*(r[0]/TARGET-1):+.2f} % | {100*(r[0]/ref[0]-1):+.2f} % | `{r[2]}` |")
    w("\n## Binding corners of the 0xA3 27-point record, P3\n")
    w("The slowest corner of the record (ss/-40 C/3.0 V) must still reach 48 MHz at the top code; the fastest "
      "(ff/85 C/3.0 V) must still be at or below 48 MHz at the bottom code. Two single-corner probes per substrate model.\n")
    w("| substrate | point | trim code | f (MHz) | need | margin | log |")
    w("|---|---|---|---|---|---|---|")
    for s_ in ("as-extracted", "hard-tied"):
        a_ = g("r070_20x10", s_, "ss:-40:3", 255)
        b_ = g("r070_20x10", s_, "ff:85:3", 0)
        if a_:
            w(f"| {s_} | ss:-40:3 | 0xFF | {a_[0]/1e6:.3f} | >= 48 | {100*(a_[0]/TARGET-1):+.1f} % | `{a_[2]}` |")
        if b_:
            w(f"| {s_} | ff:85:3 | 0x00 | {b_[0]/1e6:.3f} | <= 48 | {100*(TARGET/b_[0]-1):+.1f} % | `{b_[2]}` |")
    w("\n## Same T/V extreme probes for the alternatives (model A)\n")
    w("| candidate | process | code | point | f (MHz) | vs 48 MHz | log |")
    w("|---|---|---|---|---|---|---|")
    alt = {
        "prop_r080_17x10": {"tt": 0xAE, "ff": 0x5F, "ss": 0xDB},
        "optB_r066_24x10": {"tt": 0xAF, "ff": 0x65, "ss": 0xDB},
    }
    pts = {"tt": ["tt:27:3.3", "tt:-40:3", "tt:85:3.6"], "ff": ["ff:27:3.3", "ff:-40:3.6", "ff:85:3"], "ss": ["ss:27:3.3", "ss:-40:3", "ss:85:3.6"]}
    for c, codes in alt.items():
        for p, plist in pts.items():
            for pt in plist:
                r = g(c, "as-extracted", pt, codes[p])
                if r:
                    w(f"| `{c}` | {p} | 0x{codes[p]:02X} | {pt} | {r[0]/1e6:.3f} | {100*(r[0]/TARGET-1):+.2f} % | `{r[2]}` |")
    w("\n## Sensitivity: vc net-to-substrate C scaled with MiM area (P1 only, tt, code 0xAE)\n")
    r1, r2 = g("prop_r080_17x10", "as-extracted", "tt:27:3.3", 0xAE), g("prop_r080_17x10", "as-extracted", "tt:27:3.3", 0xAE, 0.85)
    if r1 and r2:
        w(f"vc C unscaled {r1[0]/1e6:.3f} MHz; scaled x0.85 {r2[0]/1e6:.3f} MHz ({100*(r2[0]/r1[0]-1):+.2f} %).\n")
    out.write_text("\n".join(L) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
