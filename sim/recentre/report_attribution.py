#!/usr/bin/env python3
"""Render attribution.md from an attribution run's results.csv (issue #66, AC 1).

Pure post-processing: reads results.csv, writes attribution.md next to it.
Refuses to overwrite.  Usage:
    python3 -I sim/recentre/report_attribution.py sim/recentre/results/<runid>
"""
import csv
import json
import sys
from pathlib import Path

GROUPS = ["vc_groundC", "vc_couplingC", "chain_C", "cmp_latch_C", "other_C",
          "timing_path_R", "other_R"]
LABEL = {
    "vc_groundC": "timing node `vc`: net-to-substrate C (MiM bottom-plate side + routing + comparator-input/discharge wiring)",
    "vc_couplingC": "timing node `vc`: coupling C to neighbouring nets",
    "chain_C": "trim-ladder nodes c1..c8: ground + coupling C (switch/diffusion + routing)",
    "cmp_latch_C": "comparator / SR-latch / clk nodes: ground + coupling C (comparator delay)",
    "other_C": "bias, trim-control, supply-rail nets: ground + coupling C",
    "timing_path_R": "series R, `vc` + ladder nodes (star R)",
    "other_R": "series R, all other nets",
}


def main() -> None:
    d = Path(sys.argv[1])
    out = d / "attribution.md"
    if out.exists():
        sys.exit(f"refusing to overwrite {out}")
    rows = list(csv.DictReader(open(d / "results.csv")))
    man = json.load(open(d / "manifest.json"))
    f = {(r["corner"], r["variant"]): float(r["f_hz"]) for r in rows}
    iq = {(r["corner"], r["variant"]): float(r["iq_a"]) for r in rows}
    meta = {r["corner"]: r for r in rows}
    T = lambda c, v: 1e9 / f[(c, v)] * 1.0  # period in ns (f in Hz -> 1e9/f ns)
    L = []
    w = L.append
    w(f"# Attribution of the extracted-vs-schematic slow-down (run {man['runid']})\n")
    w("Generated by `sim/recentre/report_attribution.py` from `results.csv` "
      "(driver `sim/recentre/attribute.py`, issue #66). Append-only evidence.\n")
    w(f"Source netlist: `{man['source_netlist']}` (sha256 `{man['source_netlist_sha256'][:16]}...`), "
      f"trim code {man['trim_code']} (the 27-point record's fixed code), harness `design/netlist/pvt_tb.spice`, "
      f"`{man['ngspice'][0].strip()}`, git `{man['git_sha'][:10]}`.\n")
    w("Method: single-corner transients run one at a time. Shares are in "
      "**period** (ns), the additive quantity: delay adds, frequency does not. "
      "Each item's contribution = period with the item present minus period with it "
      "removed. The telescoping table removes items in the order shown, so its rows "
      "sum to the total shift exactly; the leave-one-out table removes each item "
      "alone from the full netlist, and its sum differs from the total by the "
      "interaction term, reported as the residual.\n")
    w("Two substrate models are reported because the extractor ties the minted "
      "substrate node `vsubs` to ground only through a 1 Tohm shunt "
      "(`Rvsubs_dctie`, klt `extract_parasitics.py` issue #1263): **A** = netlist "
      "exactly as extracted (reproduces the 27-point record); **B** = same netlist "
      "with that shunt replaced by 1 mohm (a grounded p-substrate, as on silicon). "
      "The step between them is itself a row.\n")
    for cname in ("worst", "best", "centre"):
        r = meta[cname]
        fs, fe = f[(cname, "schematic")], f[(cname, "full")]
        tot = T(cname, "full") - T(cname, "schematic")
        w(f"\n## {cname}: {r['process']} / {float(r['temp_c']):g} C / {float(r['vdd_v']):g} V\n")
        w(f"schematic {fs/1e6:.3f} MHz ({T(cname,'schematic'):.3f} ns); extracted (model A) "
          f"{fe/1e6:.3f} MHz ({T(cname,'full'):.3f} ns); shift {100*(fe/fs-1):+.2f} % in frequency, "
          f"**{tot:+.3f} ns** in period. Running supply current (mean i(VDD) over the 20 measured "
          f"periods): schematic {iq[(cname,'schematic')]*1e6:.1f} uA, extracted {iq[(cname,'full')]*1e6:.1f} uA.\n")
        w("### Telescoping (cumulative removal; rows sum to the total)\n")
        w("| step removed | period before (ns) | period after (ns) | contribution (ns) | share of shift |")
        w("|---|---|---|---|---|")
        steps = [("substrate node: 1 Tohm shunt -> hard ground (A -> B)", "full", "tie_full")]
        prev = "tie_full"
        for g in GROUPS:
            steps.append((LABEL[g], prev, f"tie_cum_{g}"))
            prev = f"tie_cum_{g}"
        steps.append(("device geometry (extracted AS/AD/PS/PD, W/L, resistor lengths) vs schematic; the parasitic-free extracted devices", prev, "schematic"))
        s = 0.0
        for lab, a, b in steps:
            ta, tb = T(cname, a), T(cname, b)
            s += ta - tb
            w(f"| {lab} | {ta:.3f} | {tb:.3f} | {ta-tb:+.3f} | {100*(ta-tb)/tot:+.1f} % |")
        w(f"| **sum** | | | **{s:+.3f}** | **{100*s/tot:.1f} %** (total {tot:+.3f} ns; residual {s-tot:+.4f} ns) |\n")
        for tag, pre, full in (("A (as extracted)", "loo_", "full"), ("B (substrate hard-tied)", "tie_loo_", "tie_full")):
            w(f"### Leave-one-out, model {tag}\n")
            w("| item removed alone | f without it (MHz) | contribution (ns) | share of model's shift |")
            w("|---|---|---|---|")
            tt = T(cname, full) - T(cname, "schematic")
            ssum = 0.0
            for g in GROUPS:
                c = T(cname, full) - T(cname, pre + g)
                ssum += c
                w(f"| {LABEL[g]} | {f[(cname, pre+g)]/1e6:.3f} | {c:+.3f} | {100*c/tt:+.1f} % |")
            w(f"| sum of rows | | {ssum:+.3f} | {100*ssum/tt:.1f} % |")
            w(f"| interaction residual (model shift {tt:+.3f} ns minus sum) | | {tt-ssum:+.3f} | {100*(tt-ssum)/tt:+.1f} % |\n")
    w("\n## Reading the table\n")
    w("* Model A reproduces the 27-point record exactly at these corners "
      "(`ff/-40/3.6` -36.86 %, `ss/-40/3.6` -18.78 %, `tt/27/3.3` -25.36 %).\n"
      "* The device-geometry row is the parasitic-free extracted devices (layout "
      "AS/AD/PS/PD, drawn W/L) against the schematic devices, under the hard-tied "
      "substrate (model B); it is not zero and changes sign between corners, so it "
      "is reported, not folded into the parasitics.\n"
      "* \"Comparator input capacitance\" is a device (gate + junction) quantity that "
      "exists identically in the schematic; it cannot be removed as a parasitic. Its "
      "layout-dependent part (junction areas/perimeters) is inside the device-geometry row; "
      "its routing part is inside the `vc` net-to-substrate row, because the extractor "
      "reports one lumped C per net and cannot split MiM bottom plate from routing.\n")
    out.write_text("\n".join(L) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
