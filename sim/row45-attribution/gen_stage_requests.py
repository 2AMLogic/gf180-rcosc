#!/usr/bin/env python3
"""Stage-level attribution requests for rows 4 / 5 on the DR-0028 netlist (issue #314, DR-0033).

One `klt sim` request per (process, VDD) at that process's per-die calibration code (DR-0032 median die:
tt 165, ff 78, ss 212), each over the three temperatures.  The DUT is NOT edited: the generated copy only
appends probe pins to the `.SUBCKT` line, each tied to an internal net through a 1 mOhm resistor, so the
bench can read the stage nodes.  Writes the probed DUT copy, the benches and the requests; launches nothing.

Per (process, T, VDD) point the bench reports the absolute time of the FIRST occurrence, after TD, of the six
oscillator events (so edge-index slips from the start-up transient cannot misalign them).  stage_attribution.py
differences them modulo the period:

    vc rises through vh -> cmph_out rises   t_cmp_h   high-side comparator
    cmph_out -> clk rises                   t_lat_h   NOR-NOR latch set path
    clk rises -> vc falls through vl        t_dis     discharge through MDISCH
    vc falls through vl -> cmpl_out rises   t_cmp_l   low-side comparator
    cmpl_out -> clk falls                   t_lat_l   latch reset path
    clk falls -> vc rises through vh        t_chg     RC charge from the post-discharge level
    (sum = period)

plus vc at clk fall (charge start v0), vh, vl, the bias gate voltages (ibias, pb) and the period from three vc
rises.  Usage: python3 -I gen_stage_requests.py OUTDIR
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
sys.path.insert(0, str(REPO / "sim" / "pvt"))
from pvt_sweep import PROCESS_CORNERS, TEMPS_C, VDDS_V  # noqa: E402

SRC = REPO / "sim" / "cmph-fix" / "rcosc_top_p3_cmphfix.spice"
DUT = "rcosc_top_p3_probed.spice"
# per-die calibration code of the median die per process (DR-0032, 500-die campaign)
CODES = {"tt": 165, "ff": 78, "ss": 212}
# probe pin -> extracted net (identified from the device terminals: see the README)
PROBES = [("pvc", r"\$24"), ("pvh", r"\$5"), ("pvl", r"\$6"), ("pcmph", r"\$29"), ("pcmpl", r"\$32"),
          ("pqbar", r"\$33"), ("pibias", r"\$35"), ("ppb", r"\$7")]
SUBCKT = ".SUBCKT rcosc_top vdd vss clk t0 t1 t2 t3 t4 t5 t6 t7"
TD = "700n"
TSTOP = "1200n"


def probed_dut(text: str) -> str:
    assert text.count(SUBCKT) == 1 and text.count(".ENDS") == 1
    text = text.replace(SUBCKT, SUBCKT + " " + " ".join(p for p, _ in PROBES))
    probes = "".join(f"R{p} {p} {net} 1m\n" for p, net in PROBES)
    head, tail = text.split(".ENDS", 1)
    return head + "* probe taps (analysis only; stage_attribution, issue #314)\n" + probes + ".ENDS" + tail


def tag(proc: str, vdd: float) -> str:
    return f"{proc}_v{int(round(vdd * 10)):02d}"


def testbench(proc: str, vdd: float) -> str:
    code = CODES[proc]
    lines = [
        f"* rcosc_top stage-attribution bench, {proc} code 0x{code:02X}, VDD={vdd:g} V (generated by gen_stage_requests.py)",
        ".param sw_stat_global=0 sw_stat_mismatch=0 mc_skew=3 res_mc_skew=3 cap_mc_skew=3 fnoicor=0",
        f'.include "{DUT}"',
        "XXDUT vdd 0 clk t0 t1 t2 t3 t4 t5 t6 t7 " + " ".join(p for p, _ in PROBES) + " rcosc_top",
        f"VDD vdd 0 DC {vdd:g}",
    ]
    for i in range(8):
        lines.append(f"VT{i} t{i} 0 DC {vdd * ((code >> i) & 1):g}")
    return "\n".join(lines) + "\n"


def request(proc: str, vdd: float) -> dict:
    m = vdd / 2
    td = f"TD={TD}"

    def meas(name, expr, unit):
        return {"name": name, "spice": f".meas tran {name} {expr}", "unit": unit}

    ms = [
        meas("ev_a", f"WHEN v(pvc)=v(pvh) RISE=1 {td}", "s"),
        meas("ev_a2", f"WHEN v(pvc)=v(pvh) RISE=2 {td}", "s"),
        meas("ev_a3", f"WHEN v(pvc)=v(pvh) RISE=3 {td}", "s"),
        meas("ev_b", f"WHEN v(pcmph)={m:.4f} RISE=1 {td}", "s"),
        meas("ev_c", f"WHEN v(clk)={m:.4f} RISE=1 {td}", "s"),
        meas("ev_d", f"WHEN v(pvc)=v(pvl) FALL=1 {td}", "s"),
        meas("ev_e", f"WHEN v(pcmpl)={m:.4f} RISE=1 {td}", "s"),
        meas("ev_f", f"WHEN v(clk)={m:.4f} FALL=1 {td}", "s"),
        meas("v0", f"FIND v(pvc) WHEN v(clk)={m:.4f} FALL=1 {td}", "V"),
        meas("vh", f"AVG v(pvh) FROM=900n TO={TSTOP}", "V"),
        meas("vl", f"AVG v(pvl) FROM=900n TO={TSTOP}", "V"),
        meas("vib", f"AVG v(pibias) FROM=900n TO={TSTOP}", "V"),
        meas("vpb", f"AVG v(ppb) FROM=900n TO={TSTOP}", "V"),
        meas("vcpk", f"MAX v(pvc) FROM={TD} TO={TSTOP}", "V"),
        {"name": "f_ta", "spice": f".meas tran f_ta WHEN v(clk)={m:.4f} RISE=5", "unit": "s"},
        {"name": "f_tb", "spice": f".meas tran f_tb WHEN v(clk)={m:.4f} RISE=25", "unit": "s"},
        {"name": "fosc", "spice": ".meas tran fosc PARAM='20/(f_tb-f_ta)'", "unit": "Hz"},
    ]
    return {
        "netlist": f"tb_{tag(proc, vdd)}.spice",
        "engine": "ngspice",
        "netlist_source": "extracted",
        "models": {"pdk": "gf180mcuC", "lib": "libs.tech/ngspice/sm141064.ngspice"},
        "corners": {"process": [{"name": proc, "sections": [*PROCESS_CORNERS[proc], "cap_mim"]}],
                    "temperature_c": TEMPS_C},
        "analysis": {"kind": "tran", "args": f"200p {TSTOP}"},
        "measurements": ms,
        "batch": {"capacity_wait_s": 600},
        "options": {"timeout_s": 3600, "keep_artifacts": True, "ngspice_init": ["set measureprec=8"]},
    }


def generate(out: Path) -> list:
    out.mkdir(parents=True, exist_ok=True)
    (out / DUT).write_text(probed_dut(SRC.read_text()))
    names = []
    for proc in CODES:
        for vdd in VDDS_V:
            t = tag(proc, vdd)
            (out / f"tb_{t}.spice").write_text(testbench(proc, vdd))
            (out / f"request_{t}.json").write_text(json.dumps(request(proc, vdd), indent=2) + "\n")
            names.append(f"request_{t}.json")
    return names


if __name__ == "__main__":
    for n in generate(Path(sys.argv[1])):
        print(n)
