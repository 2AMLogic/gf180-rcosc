#!/usr/bin/env python3
"""Row 4 bank-switch Ron vs VDD / T / code (issue #317).  Writes benches + `klt sim` requests; launches nothing.

The bank is the committed schematic subckt `rcosc_trim_bank` (design/netlist/rcosc_top.spice) at ss.  Per VDD and variant
there is one bench holding KxL bank instances (K trim codes x L node levels).  Each instance has its `m` pin on a DC level
(vl = VDD/3, mid = VDD/2, vh = 2VDD/3: the span the charge node sweeps) and its `p` pin DV above it; R = DV / I(p).
Variant `real` is the committed bank; variant `ideal` replaces each bit's TG by 1 mOhm (bit set) or 1 GOhm (bit clear), which isolates
the ladder poly R at that code and corner.  Ron_eff(code, level) = R_real - R_ideal.  Usage: gen_ron_requests.py OUTDIR [WSCALE]
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
sys.path.insert(0, str(REPO / "sim" / "pvt"))
from pvt_sweep import PROCESS_CORNERS, TEMPS_C, VDDS_V  # noqa: E402

NETLIST = REPO / "design" / "netlist" / "rcosc_top.spice"
CODES = [0x00, 0x55, 0x80, 0xAA, 0xD4, 0xFF]  # 0xD4 = ss per-die calibration code (DR-0032 median die)
LEVELS = {"vl": 1 / 3, "mid": 1 / 2, "vh": 2 / 3}
DV = 0.05
PROC = "ss"


WSCALE = 1.0  # candidate switch-width scale for the `real` variant (1.0 = committed bank)


def scaled(line: str) -> str:
    """Scale W of an XSW/XPW pass device line by WSCALE (schematic ad/as/pd/ps expressions follow W)."""
    if WSCALE == 1.0 or not re.match(r"X(SW|PW)\d+ ", line):
        return line
    return re.sub(r"W=(\d+(?:\.\d+)?)uu", lambda m: f"W={float(m.group(1)) * WSCALE:g}uu", line)


def bank_text(ideal: bool, code: int = 0, name: str = "rcosc_trim_bank") -> str:
    lines = NETLIST.read_text().splitlines()
    start = next(i for i, l in enumerate(lines) if l.startswith(".subckt rcosc_trim_bank"))
    end = next(i for i in range(start, len(lines)) if lines[i].startswith(".ends"))
    body = lines[start:end + 1]
    out, i = [], 0
    while i < len(body):
        l = body[i]
        cont = [l]
        while i + 1 < len(body) and body[i + 1].startswith("+"):
            i += 1
            cont.append(body[i])
        m = re.match(r"(X(?:SW|PW)\d+)\s+(\S+)\s+\S+\s+(\S+)\s", l)
        if ideal and m:
            # ideal switch: a short when the bit is set (nfet on / pfet on), open otherwise; both halves of a TG
            # for bit i share the code bit, so XSW<i> carries the short and XPW<i> is dropped (parallel short)
            bit = (code >> int(re.search(r"\d+", m.group(1)).group())) & 1
            if m.group(1).startswith("XSW"):
                out.append(f"R{m.group(1)[1:]} {m.group(2)} {m.group(3)} {'1m' if bit else '1G'}")
        else:
            out.extend([scaled(cont[0]), *cont[1:]])
        i += 1
    return "\n".join(out).replace(".subckt rcosc_trim_bank", f".subckt {name}", 1) + "\n"


def tag(vdd: float, variant: str) -> str:
    return f"{variant}_v{int(round(vdd * 10)):02d}"


def bench(vdd: float, variant: str) -> str:
    L = [f"* rcosc_trim_bank Ron bench, {PROC}, VDD={vdd:g} V, {variant} (generated by gen_ron_requests.py)",
         ".param sw_stat_global=0 sw_stat_mismatch=0 mc_skew=3 res_mc_skew=3 cap_mc_skew=3 fnoicor=0",
         f"VDD vdd 0 DC {vdd:g}"]
    for ci, code in enumerate(CODES):
        L.append(bank_text(variant == "ideal", code, f"bank_c{ci}"))
    for ci, code in enumerate(CODES):
        for lv, fr in LEVELS.items():
            n = f"c{ci}{lv}"
            L.append(f"VM_{n} m_{n} 0 DC {vdd * fr:.6f}")
            L.append(f"VP_{n} p_{n} m_{n} DC {DV}")
            bits = " ".join(f"t{ci}b{b}" for b in range(8))
            L.append(f"XB_{n} p_{n} m_{n} 0 {bits} vdd bank_c{ci}")
        for b in range(8):
            L.append(f"VT{ci}b{b} t{ci}b{b} 0 DC {vdd * ((code >> b) & 1):g}")
    return "\n".join(L) + "\n"


def request(vdd: float, variant: str) -> dict:
    ms = [{"name": f"i_c{ci}{lv}", "spice": f".meas tran i_c{ci}{lv} AVG i(VP_c{ci}{lv}) FROM=10n TO=20n", "unit": "A"}
          for ci in range(len(CODES)) for lv in LEVELS]
    return {
        "netlist": f"tb_{tag(vdd, variant)}.spice",
        "engine": "ngspice",
        "netlist_source": "extracted",
        "models": {"pdk": "gf180mcuC", "lib": "libs.tech/ngspice/sm141064.ngspice"},
        "corners": {"process": [{"name": PROC, "sections": [*PROCESS_CORNERS[PROC], "cap_mim"]}],
                    "temperature_c": TEMPS_C},
        "analysis": {"kind": "tran", "args": "100p 20n"},
        "measurements": ms,
        "batch": {"capacity_wait_s": 600},
        "options": {"timeout_s": 1800, "keep_artifacts": True, "ngspice_init": ["set measureprec=8"]},
    }


def generate(out: Path) -> list:
    out.mkdir(parents=True, exist_ok=True)
    names = []
    for variant in ("real", "ideal"):
        for vdd in VDDS_V:
            t = tag(vdd, variant)
            (out / f"tb_{t}.spice").write_text(bench(vdd, variant))
            (out / f"request_{t}.json").write_text(json.dumps(request(vdd, variant), indent=2) + "\n")
            names.append(f"request_{t}.json")
    return names


if __name__ == "__main__":
    if len(sys.argv) > 2:
        WSCALE = float(sys.argv[2])
    for n in generate(Path(sys.argv[1])):
        print(n)
