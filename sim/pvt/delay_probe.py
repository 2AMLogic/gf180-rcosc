#!/usr/bin/env python3
"""gf180-rcosc comparator/latch delay-probe instrumentation campaign (issue #51).

Instrumentation pass, not a spec-row campaign: this driver re-uses the
``pvt_sweep.py`` deck composition but replaces the measurement with a
node-crossing decomposition of steady-state oscillation cycles, quantifying
the per-stage propagation delays DR-0003's post-trim arithmetic never
budgeted and DR-0012/DR-0014 attributed the remaining post-trim residual to:

  t_cmp_h  vc crossing vh  ->  cmph_out crossing mid-rail   (comparator, high side)
  t_lat_h  cmph_out        ->  clk rising                   (NOR-NOR latch set path)
  t_cmp_l  vc falling through vl -> cmpl_out crossing mid   (comparator, low side)
  t_lat_l  cmpl_out        ->  clk falling                  (latch reset path)
  charge   clk falling     ->  next vc crossing of vh       (the RC term, 0 -> vh)
  dsum     t_cmp_h + t_lat_h + t_cmp_l + t_lat_l            (delay paid into
                                                              the period per cycle)
  overshoot_v  max(vc) - vh                                 (the symptom of the
                                                              high-side delay, not
                                                              itself a period cost:
                                                              MDISCH resets vc to ~0)

Methodology: the transient (``tran 100p`` -- 2x finer than the campaign's
200p, for edge-resolution on the fast discharge flank) is dumped with
``wrdata`` and every crossing is extracted by linear interpolation in Python,
then events are aligned into cycles by timestamp proximity.  Edge *index*
matching (``meas ... rise=N`` across different nodes) is deliberately not
used: nodes accumulate different glitch counts during startup, which desyncs
their indices by whole cycles (observed on the ss/-40C/3.0V/0xCF cell during
this driver's own bring-up).  Several steady-state cycles are decomposed and
the per-cycle spread is reported, so a single misaligned cycle cannot pass
silently.

The point set is the two per-corner calibrated-code sets of a prior full
campaign (surrogate- and ratified-target calibration, read from that
campaign's manifest) across the same 7-process x 3-temperature x 3-supply
factorial, plus a code sweep at ``ss``/27 C that reproduces DR-0014's
per-code supply-sensitivity pairing (0x80 / 0x9D / 0xCF / 0xEF) so the
stage decomposition can be compared directly against the code-monotonicity
attribution in that record.

Evidence is append-only, same convention as ``pvt_sweep.py``:

  sim/pvt/corners/<runid>/<key>.log     per-point analysis: aligned-cycle event
                                        timestamps, derived stage delays,
                                        cross-cycle stability
  sim/pvt/results/<runid>/results.csv   one row per simulated point
  sim/pvt/results/<runid>/manifest.json provenance + probe configuration
  sim/pvt/results/<runid>/summary.md    stage-delay tables + the supply / delta-T
                                        sensitivity decomposition
"""

