#!/usr/bin/env python3
"""Offline pricing request generator for the row-2 finalists (issue #460, step 4).

Pricing = what the candidate sizing moves on the OTHER ratified rows, measured
on the **rebuilt-layout extraction** (`sim/row45-rerun/results/
20261112T200335Z-extract-l07/`, the DR-0043/0044/0045/0047 basis) with the
candidate ladder sizing applied as netlist text (variant.py; layout NOT
re-extracted, no design file touched), so the numbers are directly comparable
with the committed row-4 / row-8 baselines:

  calib  OUTDIR SIZING PROC:CODE[,...] [PROC:CODE,...]  per-die calibration scan, 27 C / 3.3 V
                                                        (same bench as sim/row45-rerun/gen_calib_requests.py)
  stage  OUTDIR SIZING tt=CODE,ff=CODE,ss=CODE          row-4 supply span: 9 requests, one per
                                                        (process, 3.0/3.3/3.6 V), each over -40/27/85 C,
                                                        at that process's calibration code (DR-0032 basis,
                                                        same shape as sim/row4-w3r65/gen.py `stage`)
  iq     OUTDIR SIZING CODE [CODE ...]                  row-8 running Iq: 12 requests, one per
                                                        (code, 3.0/3.3/3.6 V), each over tt/ff/ss x
                                                        -40/27/85 C, integrator bench (DR-0046 basis,
                                                        same shape as sim/row45-rerun/gen_row5_iq_schematic.py)

Nothing here runs a simulator; execution is run_set.py (batch fleet only).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
sys.path.insert(0, str(REPO / "sim"))
sys.path.insert(0, str(HERE))
import evidence_common  # noqa: E402
import variant  # noqa: E402

L07 = REPO / "sim" / "row45-rerun" / "results" / "20261112T200335Z-extract-l07" / "rcosc_top_p3_cmphfix.spice"
DUT = "rcosc_top_variant.spice"
MODELS = {"pdk": "gf180mcuC", "lib": "libs.tech/ngspice/sm141064.ngspice"}
PROCS = ("tt", "ff", "ss")
TEMPS = [-40.0, 27.0, 85.0]
VDDS = (3.0, 3.3, 3.6)
INTEG_LINES = ("* supply-current integrator (analysis only): v(qint) = integral of -i(VDD) dt / 1 nF\n"
               "Bint 0 qint I=-i(VDD)\nCint qint 0 1n\nRint qint 0 1e15\n.ic v(qint)=0\n")


def sections(proc: str) -> dict:
    sys.path.insert(0, str(REPO / "sim" / "pvt"))
    from pvt_sweep import PROCESS_CORNERS
    return [{"name": proc, "sections": [*PROCESS_CORNERS[proc], "cap_mim"]}]


def bench(code: int, vdd: float) -> str:
    L = [f"* row2-trimsize pricing bench, code 0x{code:02X}, VDD={vdd:g} V (generated by gen_pricing.py)",
         ".param sw_stat_global=0 sw_stat_mismatch=0 mc_skew=3 res_mc_skew=3 cap_mc_skew=3 fnoicor=0",
         f'.include "{DUT}"', "XXDUT vdd 0 clk t0 t1 t2 t3 t4 t5 t6 t7 rcosc_top", f"VDD vdd 0 DC {vdd:g}"]
    L += [f"VT{i} t{i} 0 DC {vdd * ((code >> i) & 1):g}" for i in range(8)]
    return "\n".join(L) + "\n"


def fosc_meas(vdd: float) -> list[dict]:
    m = vdd / 2
    return [{"name": "f_ta", "spice": f".meas tran f_ta WHEN v(clk)={m:.4f} RISE=5", "unit": "s"},
            {"name": "f_tb", "spice": f".meas tran f_tb WHEN v(clk)={m:.4f} RISE=25", "unit": "s"},
            {"name": "fosc", "spice": ".meas tran fosc PARAM='20/(f_tb-f_ta)'", "unit": "Hz"}]


def base_request(netlist: str, proc: str, temps: list[float], vdd: float, tstop: str) -> dict:
    return {"netlist": netlist, "engine": "ngspice", "netlist_source": "extracted",
            "models": dict(MODELS), "corners": {"process": sections(proc), "temperature_c": temps},
            "analysis": {"kind": "tran", "args": f"200p {tstop}"},
            "batch": {"capacity_wait_s": 600},
            "options": {"timeout_s": 1800, "keep_artifacts": True, "ngspice_init": ["set measureprec=8"]}}


def main() -> int:
    if len(sys.argv) < 5:
        print(__doc__)
        return 1
    mode, out, sizing = sys.argv[1], Path(sys.argv[2]), sys.argv[3]
    if mode not in ("calib", "stage", "iq"):
        print(f"error: unknown mode {mode!r}", file=sys.stderr)
        return 1
    if out.exists() and any(out.iterdir()):
        print(f"error: {out} exists and is not empty", file=sys.stderr)
        return 1
    out.mkdir(parents=True)
    dut = variant.build(L07.read_text(), sizing)
    (out / DUT).write_text(dut)
    entries = []

    def emit(corner_dir: str, stem: str, req: dict, tb: str) -> None:
        d = out / sizing / corner_dir
        d.mkdir(parents=True, exist_ok=True)
        (d / DUT).write_text(dut)   # tb .include is filename-relative: DUT lives beside the bench
        (d / req["netlist"]).write_text(tb)
        (d / f"request_{stem}.json").write_text(json.dumps(req, indent=2) + "\n")
        entries.append({"tag": f"{sizing}_{corner_dir}_{stem}", "variant": sizing, "corner": corner_dir,
                        "request": f"{sizing}/{corner_dir}/request_{stem}.json",
                        "netlist": f"{sizing}/{corner_dir}/{req['netlist']}",
                        "dut_sha256": evidence_common.sha256_bytes(dut.encode()),
                        "sha256": {"request": evidence_common.sha256_bytes((json.dumps(req, indent=2) + "\n").encode()),
                                   "netlist": evidence_common.sha256_bytes(tb.encode())}})

    if mode == "calib":
        for spec in sys.argv[4:]:
            proc, codes = spec.split(":")
            for c in codes.split(","):
                c = int(c, 0)
                net = f"tb_{proc}_c{c:02X}.spice"
                req = base_request(net, proc, [27.0], 3.3, "1200n") | {"measurements": fosc_meas(3.3)}
                emit("calib_27C_3p3V", f"{proc}_c{c:02X}", req, bench(c, 3.3))
    elif mode == "stage":
        codes = {p: int(v, 0) for p, v in (kv.split("=") for kv in sys.argv[4].split(","))}
        for proc in PROCS:
            c = codes[proc]
            for vdd in VDDS:
                net = f"tb_{proc}_v{int(round(vdd * 10)):02d}.spice"
                req = base_request(net, proc, TEMPS, vdd, "1200n") | {"measurements": fosc_meas(vdd)}
                emit("stage", f"{proc}_v{int(round(vdd * 10)):02d}", req, bench(c, vdd))
    else:  # iq
        for c in (int(a, 0) for a in sys.argv[4:]):
            for vdd in VDDS:
                vv = int(round(vdd * 10))
                net = f"tb_c{c:02X}_v{vv}.spice"
                m = vdd / 2
                req = base_request(net, "tt", TEMPS, vdd, "4000n")
                req["corners"] = {"process": [s for p in PROCS for s in sections(p)], "temperature_c": TEMPS}
                req["measurements"] = fosc_meas(vdd)[:2] + [
                    {"name": "q_a", "spice": f".meas tran q_a FIND v(qint) WHEN v(clk)={m:.4f} RISE=5", "unit": "V"},
                    {"name": "q_b", "spice": f".meas tran q_b FIND v(qint) WHEN v(clk)={m:.4f} RISE=25", "unit": "V"},
                    {"name": "iq_run", "spice": ".meas tran iq_run PARAM='(q_b-q_a)*1n/(f_tb-f_ta)'", "unit": "A"}]
                emit("iq", f"c{c:02X}_v{vv}", req, bench(c, vdd) + INTEG_LINES)

    prov = {"kind": f"row2-trimsize-pricing-{mode}-requests",
            "evidence": "NOT EVIDENCE: offline request generation, no simulation was run",
            "issue": 460, "mode": mode, "sizing": sizing, "variants": [sizing],
            "source_netlist": {"path": str(L07.relative_to(REPO)), "sha256": evidence_common.sha256_file(L07),
                               "basis": "rebuilt-layout extraction (DR-0043/0044); row-4/row-8 comparable basis"},
            "requests": entries,
            "execution": {"backend": "batch only (run_set.py); local grids forbidden (host rule)"}}
    (out / "provenance.json").write_text(json.dumps(prov, indent=2) + "\n")
    print(f"{len(entries)} {mode} requests for {sizing} -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
