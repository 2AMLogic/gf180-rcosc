"""Trim-bank sizing variants of the P3 extracted DUT (issue #460).

Netlist-text edit only, exactly the mechanism of sim/row4-nonron/variant.py
(`w<K>r<P>` edits `r_length` of base resistor X$91): the nine trim-ladder
poly resistors X$91 (RFIX) and X$92..X$99 (segments bit 0..7, DR-0023 P3
sizing) get new `r_length` values; nothing else moves.  Layout is NOT
re-extracted; the switch-width variants additionally reuse
sim/row45-rerun/variant.py `double_bank_switches` on the 16 bank pass
devices, as sim/row4-nonron/variant.py does for `w<K>`.

A sizing is named `s<RFIX>-<r0>-<r1>-...-<r7>` (lengths in um, '-'-joined) or
`s<RFIX>-<r0>-...-<r7>w<K>` with K a decimal switch-width multiplier.  The
names are generated by gen_screen.py from fit_weights.py proposals; see
sim/row2-trimsize/README.md.  `ctrl` returns the text unchanged.
"""
import importlib.util
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent.parent
# X$91 = RFIX; X$92..X$99 = segments bit 0..7 (P3 committed order).
LADDER = [(f"X${91 + i}", i) for i in range(9)]  # (instance, bit index; 9 = RFIX uses 0)
LINE = re.compile(r"^(X\$(?:9[1-9])) (.* )?r_length=([\d.]+)U r_width=2U$")
CTRL = "ctrl"


def build(text: str, name: str) -> str:
    if name == CTRL:
        return text
    m = re.fullmatch(r"s([\d.]+)((?:-[0-9.]+){8})(w\d+(?:\.\d+)?)?", name)
    if not m:
        raise ValueError(f"unknown sizing name: {name!r}")
    lengths = [float(m.group(1))] + [float(v) for v in m.group(2).split("-")[1:]]
    if any(L <= 0 for L in lengths):
        raise ValueError(f"non-positive length in {name!r}")
    lines = text.split("\n")
    seen: set[str] = set()
    for i, line in enumerate(lines):
        mm = LINE.match(line)
        if not mm:
            continue
        inst = mm.group(1)
        idx = int(inst[2:]) - 91  # 0 = RFIX, 1..8 = segment bit 0..7
        lines[i] = re.sub(r"r_length=[\d.]+U", f"r_length={lengths[idx]:.5f}U", line, count=1)
        seen.add(inst)
    if seen != {inst for inst, _ in LADDER}:
        raise ValueError(f"matched ladder instances {sorted(seen)} != X$91..X$99")
    if m.group(3):  # switch-width multiplier on the 16 bank pass devices
        k = float(m.group(3)[1:])
        spec = importlib.util.spec_from_file_location(
            "variant317", REPO / "sim" / "row45-rerun" / "variant.py")
        v317 = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(v317)
        text = "\n".join(lines)
        return v317.double_bank_switches(text, k)
    return "\n".join(lines)


def sw_mult(name: str) -> float:
    m = re.fullmatch(r"s([\d.]+)((?:-[0-9.]+){8})(w\d+(?:\.\d+)?)?", name)
    return float(m.group(3)[1:]) if m and m.group(3) else 1.0
